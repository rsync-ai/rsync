    @staticmethod
    def _normalize_since(raw) -> Optional[str]:
        """Coerce an arbitrary `since` input (str, datetime, or int/float
        epoch) into an ISO-8601 string that PG accepts in WHERE clauses.

        Returns None on unparseable input — callers degrade to full
        fetch rather than crash. See INCREMENTAL.md §3.
        """
        if raw is None:
            return None
        # datetime → isoformat
        try:
            from datetime import datetime, timezone
            if isinstance(raw, datetime):
                if raw.tzinfo is None:
                    raw = raw.replace(tzinfo=timezone.utc)
                return raw.isoformat()
        except Exception:
            pass
        # int/float → epoch seconds (or millis if very large)
        if isinstance(raw, (int, float)):
            try:
                from datetime import datetime, timezone
                ts = float(raw)
                if ts > 10_000_000_000:  # likely millis
                    ts = ts / 1000.0
                return datetime.fromtimestamp(ts, tz=timezone.utc).isoformat()
            except Exception:
                return None
        # str → trust it; PG will reject malformed timestamps at query
        # time (callers see a 500 from the SELECT, which is correct).
        if isinstance(raw, str):
            s = raw.strip()
            return s if s else None
        return None

    @staticmethod
    def _max_field_value(rows: List, field: str) -> Optional[str]:
        """Return the max value of ``field`` across rows, ISO-formatted
        when datetime-like. Returns None when no row has a non-null
        value for that field. Used to populate stats.watermark.
        """
        if not rows:
            return None
        best = None
        best_cmp = None
        from datetime import datetime
        for row in rows:
            if not isinstance(row, dict):
                continue
            v = row.get(field)
            if v is None or v == "":
                continue
            # Choose a comparable representation: datetime when possible,
            # else string (works for ISO strings + numeric strings).
            cmp_v = v
            if isinstance(v, datetime):
                cmp_v = v
            elif isinstance(v, str):
                # Best-effort parse for tie-breaking; fall back to string compare.
                try:
                    cmp_v = datetime.fromisoformat(v.replace("Z", "+00:00"))
                except Exception:
                    cmp_v = v
            if best_cmp is None or cmp_v > best_cmp:
                best_cmp = cmp_v
                best = v
        if best is None:
            return None
        if isinstance(best, datetime):
            return best.isoformat()
        return str(best)

    def export(self, params: Dict = None):
        """Export data from database. Supports incremental sync via the
        cross-connector contract documented in
        ``shared/mcp-connectors/INCREMENTAL.md`` (T2-6).

        Incremental flow when ``since`` is present:
          1. Read ``incremental_field`` (defaults to ``updated_at``).
          2. Append ``WHERE <field> > $1`` to the SQL (combined with
             any keyset condition via AND).
          3. Track ``max(<field>)`` across the batch.
          4. Return ``stats.watermark = {field, value}`` so the
             executor persists the high-water mark and replays it on
             the next scheduled run with ``mode = db_incremental``.
        """
        prepared = self.prepare_export_data(params)

        config = prepared['config']
        table = prepared.get('table')
        limit = prepared.get('limit', 10000)
        offset = prepared.get('offset', 0)
        try:
            limit = int(limit)
        except (TypeError, ValueError):
            limit = 10000
        try:
            offset = int(offset)
        except (TypeError, ValueError):
            offset = 0
        use_keyset = bool((params or {}).get("use_keyset_paging") or (params or {}).get("use_cursor_paging"))
        cursor_value = (params or {}).get("cursor")
        cursor_column = (params or {}).get("cursor_column") or (params or {}).get("primary_key")
        # PK high-water from the PREVIOUS run (INCREMENTAL.md §5). Distinct
        # from `cursor`, which is this run's paging position: `since_cursor`
        # is half of the delta predicate, `cursor` is pagination.
        since_cursor = (params or {}).get("since_cursor")

        # Incremental sync params (INCREMENTAL.md §1). Accept all four
        # alias names the executor emits (executor.go buildExportParams); pick
        # the first non-empty one. Default `incremental_field` to
        # `updated_at` — the most common DB convention. Callers that
        # use a different column should set ``incremental_field``
        # explicitly.
        raw_since = None
        for k in ("since", "updated_since", "modified_since", "modified_after"):
            v = (params or {}).get(k)
            if v:
                raw_since = v
                break
        incremental_field = str((params or {}).get("incremental_field") or "updated_at").strip()
        normalized_since = self._normalize_since(raw_since) if raw_since else None
        if raw_since and not normalized_since:
            # Malformed timestamp → fall back to full fetch (don't crash).
            try:
                import logging
                logging.warning(
                    "[Incremental] %s: malformed since value, falling back to full fetch",
                    table,
                )
            except Exception:
                pass

        if not table:
            return {"success": False, "error": "Missing 'table' parameter"}

        # Non-DBAPI warehouses (e.g., BigQuery) delegate export to an adapter.
        if getattr(self, "_warehouse_adapter", None):
            adapter_params = dict(params or {})
            adapter_params.setdefault("table", table)
            adapter_params.setdefault("limit", limit)
            return self._warehouse_adapter.export(config, adapter_params)
        
        conn = None
        try:
            conn = self._get_connection(config)
            pattern = self.driver_pattern
            
            # Handle NoSQL
            if pattern.get("is_nosql"):
                return self._export_nosql(conn, config, table, limit, offset, prepared)
            
            # SQL export
            cursor = self._get_cursor(conn)
            
            module = (self.driver_pattern.get("module", "") or "").lower()
            # Prefer keyset paging when requested or when cursor provided.
            pk = self._safe_column_identifier(str(cursor_column)) if cursor_column else None
            if (use_keyset or cursor_value is not None) and not pk:
                pk = self._get_primary_key_column(cursor, table)

            # Choose placeholder style for parameterized queries
            placeholder = "%s"
            if "sqlite" in module:
                placeholder = "?"

            # Choose identifier quoting per driver
            quote = "`" if "mysql" in module else "\""

            safe_table = self._safe_qualified_table(table, quote)
            if not safe_table:
                return {"success": False, "error": f"Unsafe table identifier: {table!r}"}

            # Incremental sync: compose the WHERE clause (see the paging-AND
            # / delta-OR note just below for how the pieces combine).
            # `inc_field_safe` is validated through `_safe_column_identifier`
            # — never interpolated directly. If validation fails, we
            # drop the incremental filter (degrade to full fetch) rather
            # than crash on a SQL syntax error.
            #
            # Two DIFFERENT fields, deliberately kept apart:
            #   * `inc_field_safe` / `inc_bind_value` drive the WHERE filter,
            #     and only exist once we have a `since` to compare against.
            #   * `watermark_field` drives the stats.watermark we REPORT, and
            #     must be populated on the very first run too.
            # Collapsing the two deadlocks the contract for DB sources: the
            # executor only sends `since` once a watermark is in the
            # checkpoint, and we only emitted a watermark once `since`
            # arrived — so neither side could ever go first and every run
            # silently degraded to keyset-by-PK (append-only), which never
            # propagates an UPDATE to an already-synced row. See
            # INCREMENTAL.md §5.
            inc_field_safe = None
            inc_bind_value = None
            watermark_field = self._safe_column_identifier(incremental_field)
            if watermark_field and normalized_since:
                inc_field_safe = watermark_field
                inc_bind_value = normalized_since

            # `cursor` is this run's PAGING position and always narrows with
            # AND. The delta predicate below decides which rows this run
            # cares about at all, and its two halves are OR'ed:
            #
            #     WHERE pk > <page cursor>
            #       AND ( updated_at > <watermark> OR pk > <last run's pk> )
            #
            # The OR is the whole fix. Timestamp alone would drop every
            # INSERT whose incremental column is NULL or hand-maintained.
            # AND-ing the two halves (the behavior this replaces) dropped
            # every UPDATE to an already-synced row, because an updated row
            # keeps its old PK and so can never satisfy `pk > last_pk` —
            # source and destination diverged silently, with the run still
            # reporting success. Only the OR catches both shapes.
            where_parts = []
            bind_values = []
            if pk and cursor_value is not None and cursor_value != "":
                where_parts.append(f"{quote}{pk}{quote} > {placeholder}")
                bind_values.append(cursor_value)

            delta_parts = []
            delta_values = []
            if inc_field_safe is not None and inc_bind_value is not None:
                delta_parts.append(f"{quote}{inc_field_safe}{quote} > {placeholder}")
                delta_values.append(inc_bind_value)
            if pk and since_cursor is not None and since_cursor != "":
                delta_parts.append(f"{quote}{pk}{quote} > {placeholder}")
                delta_values.append(since_cursor)
            if delta_parts:
                where_parts.append("(" + " OR ".join(delta_parts) + ")")
                bind_values.extend(delta_values)

            where_clause = ""
            if where_parts:
                where_clause = " WHERE " + " AND ".join(where_parts)

            if pk:
                query = f"SELECT * FROM {safe_table}{where_clause} ORDER BY {quote}{pk}{quote} LIMIT {limit}"
                cursor.execute(query, tuple(bind_values) if bind_values else None)
            else:
                # No PK → fall back to OFFSET paging. Still honors the
                # incremental WHERE if present.
                query = f"SELECT * FROM {safe_table}{where_clause} LIMIT {limit} OFFSET {offset}"
                cursor.execute(query, tuple(bind_values) if bind_values else None)
            
            # Convert rows to dicts
            columns = [desc[0] for desc in cursor.description] if cursor.description else []
            rows = cursor.fetchall()
            
            if rows and isinstance(rows[0], dict):
                data = rows
            else:
                data = [dict(zip(columns, row)) for row in rows]
            
            cursor.close()
            # Include next_cursor for keyset pagination if we can.
            next_cursor = None
            if pk and data:
                last = data[-1]
                if isinstance(last, dict):
                    next_cursor = last.get(pk)
                else:
                    try:
                        idx = columns.index(pk)
                        next_cursor = last[idx]
                    except Exception:
                        next_cursor = None

            result = self.finalize_export_result(data, prepared, columns)
            if next_cursor is not None:
                result["next_cursor"] = next_cursor
                result["paging_mode"] = "keyset"
                result["cursor_column"] = pk

            # Incremental watermark (T2-6). Emitted whenever the
            # incremental field is a REAL column on this table — including
            # the first run, when no `since` has been supplied yet. That
            # first emission is what bootstraps the contract; without it a
            # DB source can never enter incremental mode at all.
            #
            # `columns` comes from cursor.description, so this is an
            # existence check against the actual result set: a table with
            # no `updated_at` emits no watermark and correctly stays on the
            # append-only keyset path. Matched case-insensitively because
            # Oracle and friends fold identifiers, and we report the
            # column's real spelling so the next run's WHERE clause binds
            # against a name the driver recognizes.
            #
            # Edge cases (INCREMENTAL.md §3):
            #   * Field absent from the table → omit watermark.
            #   * Since present AND 0 rows → echo `since` (don't clear
            #     the checkpoint just because nothing changed).
            #   * Rows present → emit max(incremental_field).
            watermark_col = None
            if watermark_field:
                for col in (columns or []):
                    if str(col).lower() == watermark_field.lower():
                        watermark_col = col
                        break
            if watermark_col is not None:
                max_val = self._max_field_value(data, watermark_col)
                if max_val is None and normalized_since:
                    max_val = normalized_since
                if max_val is not None:
                    result.setdefault("stats", {})
                    result["stats"]["watermark"] = {
                        "field": watermark_col,
                        "value": max_val,
                    }
                    # Surface flat too for tooling that doesn't read
                    # stats.watermark (mirrors Shopify connector).
                    result["max_watermark"] = max_val
            return result
            
        except Exception as e:
            return {"success": False, "error": str(e)}
        finally:
            if conn:
                try:
                    conn.close()
                except:
                    pass
    
    def _export_nosql(self, conn, config: Dict, collection: str, limit: int, offset: int, prepared: Dict) -> Dict:
        """Export from NoSQL database"""
        if "mongo" in self.driver_pattern.get("module", ""):
            import json
            from bson.json_util import dumps
            
            database = config.get("database")
            db = conn[database]
            coll = db[collection]
            
            docs = list(coll.find().skip(offset).limit(limit))
            data = json.loads(dumps(docs))
            
            return self.finalize_export_result(data, prepared)
        
        return {"success": False, "error": "Export not supported for this NoSQL database"}
    
