def _pg_bind_value(v: Any, canonical_type: Optional[str] = None) -> Any:
    """Coerce a Python value for psycopg2 parameter binding.

    When ``canonical_type`` is provided, the coercion is dialect-aware:
      - ``json``:      None/empty-string -> NULL; dict/list -> JSON
                       text; bare strings get passed through (already
                       JSON) when they look JSON-shaped, else wrapped.
      - other types:   only non-scalar Python values (dict/list) get
                       JSON-serialised; scalars pass through.

    Without ``canonical_type``, falls back to the generic
    "dict/list -> json.dumps" rule. Always preserves None.
    """
    if v is None:
        return None
    ct = (canonical_type or "").strip().lower()
    if ct == "json":
        # JSONB rejects empty strings. Coerce to NULL so the pipeline
        # doesn't fail on Shopify GraphQL fields that emit "" for
        # absent values (descriptionHtml, note, ...).
        if isinstance(v, str):
            stripped = v.strip()
            if stripped == "":
                return None
            # Already JSON-shaped — trust it.
            if stripped[:1] in ("{", "[", '"') or stripped in ("null", "true", "false"):
                return stripped
            # Plain string into JSON column: wrap as JSON string literal.
            return json.dumps(v)
        if isinstance(v, (dict, list)):
            try:
                return json.dumps(v, default=str)
            except (TypeError, ValueError):
                return json.dumps(str(v))
        # Numbers / booleans / etc. — let json.dumps decide.
        try:
            return json.dumps(v, default=str)
        except (TypeError, ValueError):
            return json.dumps(str(v))
    # Non-JSON columns: only nested values need explicit serialization.
    if isinstance(v, (dict, list)):
        try:
            return json.dumps(v, default=str)
        except (TypeError, ValueError):
            return str(v)
    return v


def _pg_copy_render_field(bound: Any) -> Optional[str]:
    """Render a value *already coerced by _pg_bind_value* to COPY CSV text.

    Returns ``None`` to signal a SQL NULL (the caller emits an empty,
    unquoted field for it). Every non-None value is returned as text and the
    caller double-quotes it, so an empty string survives as a quoted ``""``
    (empty string, not NULL) — the one ambiguity CSV COPY otherwise gets
    wrong. The text representations are chosen so PostgreSQL's COPY parser,
    binding into the *target column's own type*, yields the identical stored
    value the ``executemany`` adapter produces.
    """
    if bound is None:
        return None
    if isinstance(bound, bool):
        return 't' if bound else 'f'
    if isinstance(bound, float):
        # PG accepts NaN/Infinity/-Infinity (capitalized) for float columns;
        # str(float) is the shortest round-trip repr otherwise.
        if not math.isfinite(bound):
            return 'NaN' if math.isnan(bound) else ('Infinity' if bound > 0 else '-Infinity')
        return repr(bound)
    if isinstance(bound, (int, Decimal)):
        return str(bound)
    if isinstance(bound, (datetime, date, time)):
        return bound.isoformat()
    if isinstance(bound, (bytes, bytearray, memoryview)):
        # bytea hex input format; CSV passes the backslash through verbatim.
        return '\\x' + bytes(bound).hex()
    return str(bound)


def _build_pg_copy_csv(rows: List[Dict[str, Any]], columns: List[str],
                       col_types: Optional[Dict[str, Any]] = None) -> str:
    """Serialize rows to a PostgreSQL ``FORMAT csv`` COPY payload.

    Reuses :func:`_pg_bind_value` for the exact JSON / NULL / case coercion
    the ``executemany`` path applies, then renders each value to CSV text.
    Encoding rules (PG CSV dialect): NULL is an empty *unquoted* field; every
    non-NULL field is wrapped in double quotes with embedded ``"`` doubled to
    ``""``. Always-quoting non-NULL fields is what keeps an empty string (``""``)
    distinct from NULL (empty) — the classic COPY-CSV footgun.
    """
    col_types = col_types or {}
    lines: List[str] = []
    for row in rows:
        fields: List[str] = []
        for col in columns:
            bound = _pg_bind_value(row.get(col), col_types.get(col))
            text = _pg_copy_render_field(bound)
            if text is None:
                fields.append('')  # NULL
            else:
                fields.append('"' + text.replace('"', '""') + '"')
        lines.append(','.join(fields))
    return ('\n'.join(lines) + '\n') if lines else ''


