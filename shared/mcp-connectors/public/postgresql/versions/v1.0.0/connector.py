    def import_data(self, params: Dict = None):
        """Import data into database"""
        prepared = self.prepare_import_data(params)
        
        if not prepared.get('success', True):
            return prepared
        
        data = prepared.get('data', [])
        if not data:
            return {"success": True, "rows_inserted": 0, "message": "No data to import"}
        
        config = prepared['config']
        table = prepared.get('table')
        
        if not table:
            return {"success": False, "error": "Target table not specified"}
        # PostgreSQL normalization is a no-op for other drivers. Pass params so a
        # bare table + per-pipeline namespace resolves to the right schema (the
        # insert/upsert/delete paths all share this so they stay consistent).
        table = self._normalize_table_for_postgresql(config, table, params)
        # Fail-closed write-path SQLi guard: the (tenant-controlled) destination
        # table is interpolated raw into INSERT/MERGE/DELETE below (and via
        # _qualified_quoted_table). Reject an unsafe identifier before ANY raw
        # {table} interpolation — mirrors the read-path (export) guard.
        if self._safe_qualified_table(table) is None:
            return {"success": False, "error": f"Unsafe table identifier: {table!r}"}

        # Non-DBAPI warehouses (e.g., BigQuery) delegate import to an adapter.
        if getattr(self, "_warehouse_adapter", None):
            adapter_params = dict(params or {})
            adapter_params.setdefault("table", table)
            adapter_params.setdefault("data", data)
            return self._warehouse_adapter.import_data(config, adapter_params)
        
        conn = None
        try:
            conn = self._get_connection(config)
            pattern = self.driver_pattern
            
            # Handle NoSQL
            if pattern.get("is_nosql"):
                return self._import_nosql(conn, config, table, data)
            
            # SQL import
            cursor = self._get_cursor(conn, as_dict=False)
            
            if data:
                columns = list(data[0].keys())
                placeholders = ", ".join(["%s"] * len(columns))
                # Quote identifiers so case-sensitive columns (createdAt,
                # totalInventory, etc.) match what ensure_table() created.
                # Postgres folds unquoted identifiers to lowercase, which
                # used to silently mismatch columns the sink had created
                # via quoted DDL.
                col_str = ", ".join([f'"{c}"' for c in columns])

                insert_query = f"INSERT INTO {self._qualified_quoted_table(table)} ({col_str}) VALUES ({placeholders})"

                # Pick up per-column canonical types if the orchestrator
                # passed them in. Used by _pg_bind_value for type-aware
                # coercion (e.g. "" -> NULL for JSONB).
                col_types = (params or {}).get("column_types") or {}
                if not isinstance(col_types, dict):
                    col_types = {}

                # Bulk-load via COPY when enabled (default-off), else the
                # byte-identical paged executemany path. COPY is INSERT-only,
                # straight into the target — import_data has no ON CONFLICT, so
                # no staging/merge is needed (that path lives in upsert_data).
                if self._pg_bulk_copy_enabled(params):
                    rows_inserted = self._copy_import_rows(
                        cursor, table, columns, data, col_types
                    )
                else:
                    # Batch insert
                    rows_inserted = 0
                    batch_size = min(self.max_batch_size, 1000)

                    for i in range(0, len(data), batch_size):
                        batch = data[i:i + batch_size]
                        values = [
                            tuple(
                                _pg_bind_value(row.get(col), col_types.get(col))
                                for col in columns
                            )
                            for row in batch
                        ]
                        cursor.executemany(insert_query, values)
                        # Count rows the DB actually wrote (cursor.rowcount), NOT len(batch).
                        # Returning len(batch) unconditionally masked silent data loss: a write
                        # that affected 0 rows still reported success+N, the sink ack'd it, and
                        # the pipeline reported "completed" with 0 rows landed. Fall back to
                        # len(batch) only when the driver doesn't report a count (rowcount < 0).
                        affected = cursor.rowcount
                        rows_inserted += affected if (affected is not None and affected >= 0) else len(batch)

                # Diagnostic: resolved target + connected DB + submitted-vs-affected.
                # A shortfall (affected < submitted) is the silent-data-loss signature.
                _curdb = getattr(getattr(conn, "info", None), "dbname", "?")
                logger.info(
                    "import_data: target=%s db=%s submitted=%d affected=%d",
                    table, _curdb, len(data), rows_inserted,
                )

                # Persist the Kafka high-water offset in the SAME transaction as the
                # inserted rows so data + progress commit atomically (exactly-once for
                # append-only CDC, replaces Redis dedup). No-op for full-load callers,
                # which do not supply kafka_offset.
                self._write_cdc_offsets(cursor, params)
                conn.commit()

            cursor.close()
            return {"success": True, "rows_inserted": rows_inserted}
            
        except Exception as e:
            if conn:
                try:
                    conn.rollback()
                except:
                    pass
            return {"success": False, "error": str(e)}
        finally:
            if conn:
                try:
                    conn.close()
                except:
                    pass
    
    # Canonical type vocabulary → PostgreSQL DDL types. The discovery
    # contract (shared/mcp-connectors/schemas/response_schemas.py) defines
    # the canonical names every source connector must emit. Sinks are the
    # only place that knows its dialect — sources stay generic.
    # Canonical->PostgreSQL DDL mapping (and raw-MySQL-dialect folding) now lives
    # in the shared `canonical_to_ddl("postgresql", ...)` authority — see
    # `_pg_type_for`. The old per-connector `_CANONICAL_TO_PG` /
    # `_MYSQL_DIALECT_TO_CANONICAL` tables were removed to end the cross-sink
    # drift (they were the same class of duplicate that #530/#535 consolidated).

    # PostgreSQL DDL type bases that the kafka-mcp-sink emits already-resolved
    # in the CDC path (deriveColumnTypesForDestination → mapConnectFieldToDDLType).
    # These must be used VERBATIM, never re-mapped through the canonical/MySQL
    # dialect tables (which would corrupt JSONB→TEXT, TIMESTAMPTZ→TEXT, etc.).
    _CDC_PG_DDL_BASES = frozenset({
        "smallint", "integer", "int", "bigint",
        "real", "double precision", "numeric", "decimal",
        "boolean", "bool", "bytea", "jsonb", "json", "uuid", "text",
        "char", "varchar", "character", "character varying",
        "date", "time", "timestamp", "timestamptz",
        "time with time zone", "time without time zone",
        "timestamp with time zone", "timestamp without time zone",
    })

    def _cdc_ddl_type(self, t) -> str:
        """Resolve a column type for the CDC write path (``_ensure_table_for_cdc``).

        The kafka-mcp-sink already maps Debezium logical types to final
        PostgreSQL DDL (``DOUBLE PRECISION``, ``JSONB``, ``TIMESTAMPTZ``,
        ``BYTEA``, ``NUMERIC(38,4)``, exact integer widths, …). Accept those
        verbatim — including parametric detail like ``NUMERIC(38,4)`` — so we
        do NOT lose what the sink already derived. Only canonical names or a
        missing hint fall through to ``_pg_type_for`` (→ TEXT for unknowns).

        This is deliberately CDC-only: the snapshot/batch path (``ensure_table``)
        receives canonical source types and keeps using ``_pg_type_for`` directly,
        so the ambiguous ``timestamp`` (canonical→TIMESTAMPTZ vs DDL→TIMESTAMP)
        cannot cross paths.
        """
        if isinstance(t, str) and t.strip():
            raw = t.strip()
            base = raw.lower().split("(")[0].strip()
            if base in self._CDC_PG_DDL_BASES:
                return raw
            return self._pg_type_for(raw)
        return "TEXT"

    def _pg_type_for(self, canonical: str) -> str:
        """Return the PostgreSQL DDL type for a canonical type name.

        Delegated to the shared `canonical_to_ddl("postgresql", ...)` authority
        (single source of truth across every sink), which handles canonical names
        AND raw MySQL-dialect tokens (via its internal `canonicalize_type`) —
        decimal->NUMERIC(38,9), number->DOUBLE PRECISION, json->JSONB, timestamp->
        TIMESTAMPTZ, binary->BYTEA, unknown->TEXT, etc. Two PG-specific behaviors
        are preserved locally because they sit OUTSIDE the canonical vocabulary:

          0. an explicit ``numeric(p,s)``/``decimal(p,s)`` is returned VERBATIM so
             the exact scale (and the source's spelling) survives a PG round trip;
             bare ``decimal``/``numeric`` fall through to the shared authority
             (-> NUMERIC(38,9), never PG's scale-0 default);
          1. a raw ``uuid`` token -> native ``UUID`` (the canonical vocabulary
             collapses uuid->string; only a non-canonical source still emits the
             raw token, and PG's native UUID beats CHAR(36)/TEXT for `=`/`::uuid`).
        """
        if not isinstance(canonical, str):
            return "TEXT"
        raw = canonical.strip()
        low = raw.lower().split("(")[0].strip()
        if low in ("numeric", "decimal") and "(" in raw:
            return raw
        if low == "uuid":
            return "UUID"
        return canonical_to_ddl("postgresql", raw)

    # Current base type → set of safe, NON-LOSSY widened PostgreSQL base types.
    # The symmetric analogue of the MySQL connector's _WIDEN. Only these promotions
    # are auto-applied when an EXISTING destination column's type differs from the
    # desired type (approved drift type-change apply + batch re-derivation). Narrowing,
    # lossy, or cross-family casts are intentionally ABSENT — they are left to a manual
    # migration rather than risking data corruption (e.g. bigint→double precision loses
    # precision for large integers; numeric→double is lossy; text→timestamp can fail on
    # bad data). Keys/values use the information_schema.data_type vocabulary that
    # _normalize_pg_ddl_type folds both the introspected current type AND the desired
    # DDL type into.
    _PG_WIDEN = {
        "smallint":                    {"integer", "bigint", "real", "double precision", "numeric", "text"},
        "integer":                     {"bigint", "double precision", "numeric", "text"},
        "bigint":                      {"numeric", "text"},
        "real":                        {"double precision", "numeric", "text"},
        "double precision":            {"numeric", "text"},
        "numeric":                     {"text"},
        "character":                   {"character varying", "text"},
        "character varying":           {"text"},
        "date":                        {"timestamp without time zone", "timestamp with time zone", "text"},
        "timestamp without time zone": {"timestamp with time zone", "text"},
        "timestamp with time zone":    {"text"},
        "boolean":                     {"text"},
        "uuid":                        {"text"},
    }

    def _normalize_pg_ddl_type(self, t) -> str:
        """Fold a PostgreSQL DDL type OR an information_schema.data_type into a
        canonical base keyword so the DESIRED type (a DDL string like "DOUBLE
        PRECISION"/"BIGINT"/"NUMERIC(38,9)") and the CURRENT type (introspected from
        information_schema, e.g. "double precision"/"bigint"/"numeric") compare on the
        same axis. Lowercases, strips precision/params, and maps spelling aliases onto
        the information_schema vocabulary used as _PG_WIDEN keys."""
        s = str(t or "").strip().lower()
        base = s.split("(")[0].strip()
        aliases = {
            "timestamptz": "timestamp with time zone",
            "timestamp": "timestamp without time zone",
            "varchar": "character varying",
            "char": "character",
            "bpchar": "character",
            "int": "integer",
            "int2": "smallint",
            "int4": "integer",
            "int8": "bigint",
            "serial": "integer",
            "bigserial": "bigint",
            "float4": "real",
            "float8": "double precision",
            "bool": "boolean",
            "decimal": "numeric",
        }
        return aliases.get(base, base)

    def ensure_table(self, params: Dict = None) -> Dict[str, Any]:
        """Create / migrate the destination table for a pipeline write.

        Generic across all source connectors that follow the canonical
        discovery contract. The orchestrator calls this before the first
        INSERT batch with the column list + types pulled from
        discover_schema(). Idempotent — safe to call on every run.

        Params:
            config:        Database connection config.
            table:         Destination table (optionally schema-qualified).
            columns:       List of column names that will be inserted.
            column_types:  Optional dict {name: canonical_type}. Columns
                           missing a type entry default to TEXT (canonical
                           "string"). Sources that emit canonical via
                           discover_schema populate this; legacy callers
                           that pass names-only still work.
            key_fields:    Primary key columns. Used to create a UNIQUE
                           index supporting upserts. Empty list is fine —
                           the table is still created.

        Returns: ``{success, table}`` on success, ``{success: False, error}``
        on failure. The orchestrator already swallows "method not found"
        gracefully, so connectors that don't implement this won't break.
        """
        params = params or {}
        config = self._get_config(params) if hasattr(self, "_get_config") else (params.get("config") or {})
        table = str(params.get("table") or "").strip()
        if not table:
            return {"success": False, "error": "Missing table"}

        cols_raw = params.get("columns") or []
        columns: List[str] = []
        if isinstance(cols_raw, list):
            for c in cols_raw:
                cc = str(c or "").strip()
                if cc:
                    columns.append(cc)

        col_types_raw = params.get("column_types") or {}
        column_types: Dict[str, str] = {}
        if isinstance(col_types_raw, dict):
            for k, v in col_types_raw.items():
                if k and v:
                    column_types[str(k)] = str(v)

        keys_raw = params.get("key_fields") or params.get("keys") or []
        key_fields: List[str] = []
        if isinstance(keys_raw, list):
            for c in keys_raw:
                cc = str(c or "").strip()
                if cc:
                    key_fields.append(cc)

        # Synthetic-PK fallback. When the source didn't declare any PKs
        # we inject ``_rsync_row_hash`` (TEXT) + ``_rsync_synced_at``
        # (TIMESTAMPTZ) — see SYNTHETIC_PK_COL / SYNTHETIC_TS_COL — and
        # use the row hash as the upsert key. Mirrors Fivetran's
        # approach so PK-less sources still get idempotent reruns.
        # The orchestrator sets ``synthetic_pk: true`` once it sees
        # the source has no real PKs; that flag also surfaces back to
        # the response so import_data / upsert_data can compute hashes
        # without re-introspecting.
        # Append-only history mode (CDC sink, cdc_write_mode=append): the table is
        # INSERT-only and stores every change version, so it must have NO PK/unique
        # index — neither a business key nor a synthetic _rsync_row_hash. The worker
        # signals this with synthetic_pk=false (+ append_mode=true). An EXPLICIT
        # synthetic_pk=False (or append_mode=True) is a hard opt-out of the fallback,
        # even though key_fields is empty.
        _append_mode = bool(params.get("append_mode"))
        _synthetic_pk_param = params.get("synthetic_pk")
        _synthetic_pk_disabled = (_synthetic_pk_param is False) or _append_mode
        synthetic_pk_requested = (
            bool(_synthetic_pk_param) or (not key_fields)
        ) and not _synthetic_pk_disabled
        synthetic_pk_applied = False
        if synthetic_pk_requested and not key_fields:
            if SYNTHETIC_PK_COL not in columns:
                columns.append(SYNTHETIC_PK_COL)
            if SYNTHETIC_TS_COL not in columns:
                columns.append(SYNTHETIC_TS_COL)
            column_types.setdefault(SYNTHETIC_PK_COL, "string")
            column_types.setdefault(SYNTHETIC_TS_COL, "timestamp")
            key_fields = [SYNTHETIC_PK_COL]
            synthetic_pk_applied = True

        # Default-include any key field that wasn't in `columns` — they
        # must exist for the unique index to bind. Avoids silently dropping
        # PKs when the caller only sent inferred columns.
        for k in key_fields:
            if k not in columns:
                columns.append(k)

        safe_cols = [c for c in columns if self._is_safe_ident(c)]
        if not safe_cols:
            return {"success": False, "error": "No safe columns to create destination table"}

        # A BARE table arrives with the per-pipeline destination schema forwarded
        # separately as params["namespace"] / params["db_or_schema"] (the sink sends
        # a bare name so single-namespace dests resolve the DB from config). ensure_table
        # MUST honor it the same way upsert_data / import_data / drop_table do (via
        # _normalize_table_for_postgresql) — otherwise it CREATEs public.<table> while
        # the write targets <namespace>.<table>, the per-pipeline schema is never created,
        # every INSERT fails with `schema "<ns>" does not exist`, the batch is DLQ'd, and
        # the load silently loses ALL rows. (Root-caused on shopify→pg staging run
        # 2384ebdd: ensure made public.products, upsert wrote rsync_shopify_2384ebdd.products.)
        table = self._normalize_table_for_postgresql(config, table, params)
        # Resolve {schema, name} from the table spec. _split_schema_table
        # is the connector's existing helper used by upsert/import paths.
        schema, name = self._split_schema_table(table)
        if not self._is_safe_ident(schema) or not self._is_safe_ident(name):
            return {"success": False, "error": f"Unsafe destination identifier: {schema}.{name}"}

        conn = None
        try:
            conn = self._get_connection(config)
            cursor = self._get_cursor(conn, as_dict=False)

            cursor.execute(f'CREATE SCHEMA IF NOT EXISTS "{schema}"')

            # Per-pipeline namespace ownership tracking. The
            # _rsync_pipelines table lives in public.* (see
            # .design/destination-namespace.md) and lets reload-mode
            # drop_table refuse to nuke another pipeline's tables.
            # Backward-compat: only insert when pipeline_id is supplied
            # by the orchestrator (older orchestrators omit it).
            pipeline_id = (
                params.get("pipeline_id")
                or (params.get("config") or {}).get("pipeline_id")
                or ""
            )
            pipeline_id = str(pipeline_id).strip()
            cursor.execute(
                'CREATE TABLE IF NOT EXISTS public._rsync_pipelines ('
                'pipeline_id TEXT PRIMARY KEY, '
                'namespace TEXT NOT NULL, '
                'created_at TIMESTAMPTZ DEFAULT NOW())'
            )
            cursor.execute(
                'CREATE INDEX IF NOT EXISTS idx_rsync_pipelines_namespace '
                'ON public._rsync_pipelines(namespace)'
            )
            if pipeline_id and schema:
                cursor.execute(
                    'INSERT INTO public._rsync_pipelines (pipeline_id, namespace) '
                    'VALUES (%s, %s) ON CONFLICT (pipeline_id) DO NOTHING',
                    (pipeline_id, schema),
                )

            # CDC writers (kafka-mcp-sink) pre-resolve each column to a FINAL
            # PostgreSQL DDL type (DOUBLE PRECISION, JSONB, TIMESTAMPTZ, BYTEA,
            # NUMERIC(38,4), exact integer widths, …) and set types_are_ddl=true.
            # Those must be honoured verbatim — re-running them through
            # _pg_type_for (which expects CANONICAL source names like "double",
            # "json", "timestamp") silently collapses every non-coincidental DDL
            # type to TEXT (the double-mapping bug). The batch/snapshot executor
            # sends canonical names with no flag, so it keeps using _pg_type_for.
            _types_are_ddl = bool(params.get("types_are_ddl"))

            def _resolve_col_type(col):
                raw = column_types.get(col, "string")
                return self._cdc_ddl_type(raw) if _types_are_ddl else self._pg_type_for(raw)

            col_defs_parts = []
            for c in safe_cols:
                col_defs_parts.append(f'"{c}" {_resolve_col_type(c)}')
            col_defs = ", ".join(col_defs_parts)
            cursor.execute(f'CREATE TABLE IF NOT EXISTS "{schema}"."{name}" ({col_defs})')

            # Idempotent schema-migration: add any columns missing on an
            # existing table. The IF NOT EXISTS guards reruns.
            for c in safe_cols:
                cursor.execute(
                    f'ALTER TABLE "{schema}"."{name}" '
                    f'ADD COLUMN IF NOT EXISTS "{c}" {_resolve_col_type(c)}'
                )

            # Idempotent SAFE widening: when an EXISTING destination column's type
            # differs from the desired type and the change is a NON-LOSSY widening
            # (per _PG_WIDEN), ALTER it in place. This is what makes an APPROVED drift
            # type-change actually apply (KI-DRIFT-TYPECHANGE-APPLY-FAILS) — the ADD
            # COLUMN loop above no-ops on an existing column, so without this a
            # type change would silently do nothing. Mirrors the MySQL connector's
            # existing _WIDEN behavior so both engines evolve dest types symmetrically.
            # strict_type_change (set by the healer's approved-type-change path) makes a
            # requested change that is NOT a safe widening raise a clear error instead of
            # a silent no-op — the user approved a cast that can't be applied safely and
            # must be told. The batch/CDC write path leaves it unset → best-effort (skip),
            # preserving write robustness.
            _strict_type_change = bool(params.get("strict_type_change"))
            _requested_types = column_types or {}
            cursor.execute(
                "SELECT column_name, data_type FROM information_schema.columns "
                "WHERE table_schema = %s AND table_name = %s",
                (schema, name),
            )
            _existing_pg_types = {}
            for _row in cursor.fetchall() or []:
                # cursor is as_dict=False here → tuple rows (column_name, data_type).
                if isinstance(_row, (list, tuple)) and len(_row) >= 2:
                    _existing_pg_types[str(_row[0])] = str(_row[1]).lower()
            for c in safe_cols:
                # Only reconcile columns the caller actually specified a type for.
                if c not in _requested_types:
                    continue
                _current = self._normalize_pg_ddl_type(_existing_pg_types.get(c, ""))
                if not _current:
                    continue  # brand-new column — already handled by ADD COLUMN above
                _desired_ddl = _resolve_col_type(c)
                _desired = self._normalize_pg_ddl_type(_desired_ddl)
                if not _desired or _desired == _current:
                    continue
                if _desired in self._PG_WIDEN.get(_current, set()):
                    try:
                        cursor.execute("SAVEPOINT _rsync_widen")
                        cursor.execute(
                            f'ALTER TABLE "{schema}"."{name}" '
                            f'ALTER COLUMN "{c}" TYPE {_desired_ddl} USING "{c}"::{_desired_ddl}'
                        )
                        cursor.execute("RELEASE SAVEPOINT _rsync_widen")
                    except Exception as _widen_err:
                        # A whitelisted widening should always cast; never let an
                        # unexpected failure abort the whole ensure_table tx (it also
                        # serves the batch write path). Roll back only this statement.
                        try:
                            cursor.execute("ROLLBACK TO SAVEPOINT _rsync_widen")
                            cursor.execute("RELEASE SAVEPOINT _rsync_widen")
                        except Exception:
                            pass
                        if _strict_type_change:
                            raise Exception(
                                f'column "{c}": widening {_current} -> {_desired} '
                                f'failed: {_widen_err}'
                            )
                elif _strict_type_change:
                    raise Exception(
                        f'column "{c}": type change {_current} -> {_desired} is not a '
                        f'safe non-lossy widening; apply this migration manually'
                    )

            # Unique index on key fields enables ON CONFLICT upserts.
            # Empty key_fields → no index (INSERT-only mode; sink may
            # synthesize a hash PK in a later patch).
            safe_keys = [c for c in key_fields if self._is_safe_ident(c)]
            if safe_keys:
                idx = self._mk_index_name(schema, name, safe_keys)
                cols_sql = ", ".join([f'"{c}"' for c in safe_keys])
                cursor.execute(
                    f'CREATE UNIQUE INDEX IF NOT EXISTS "{idx}" '
                    f'ON "{schema}"."{name}" ({cols_sql})'
                )

                # Set REPLICA IDENTITY USING INDEX so the table is valid
                # for logical replication / publications. Without this,
                # if any publication exists on the destination DB (e.g.
                # leftover from a prior CDC pipeline FOR ALL TABLES),
                # every UPDATE — including ON CONFLICT DO UPDATE upserts —
                # fails with:
                #
                #   cannot update table because it does not have a
                #   replica identity and publishes updates
                #
                # The unique-not-null index is the standard substitute
                # for a PRIMARY KEY in logical replication. NOT NULL on
                # the indexed columns is required by PG for this; we
                # enforce it before setting the identity.
                # NOT NULL on the key cols is required for REPLICA IDENTITY USING
                # INDEX. On a PRE-EXISTING table the key column may have just been
                # ADDED above (so existing rows are NULL) — SET NOT NULL then fails.
                # Scope that failure to a SAVEPOINT, never a full conn.rollback():
                # a whole-tx rollback would also undo the ADD COLUMN + unique index
                # above, leaving the destination MISSING the key column so every
                # later upsert dies with `column "<key>" does not exist`, 0 rows
                # land, and the sink records a silent "degraded" — the full-table
                # drop on dest schema drift (Bug A). The just-added column + index
                # must survive; we only forgo the NOT NULL / non-DEFAULT identity.
                for c in safe_keys:
                    try:
                        cursor.execute("SAVEPOINT _rsync_setnn")
                        cursor.execute(
                            f'ALTER TABLE "{schema}"."{name}" ALTER COLUMN "{c}" SET NOT NULL'
                        )
                        cursor.execute("RELEASE SAVEPOINT _rsync_setnn")
                    except Exception:
                        # Pre-existing NULLs block this; keep the column + index
                        # (roll back ONLY this statement) and fall back to DEFAULT
                        # replica identity. upserts still work unless a publication
                        # actually requires a non-DEFAULT identity.
                        try:
                            cursor.execute("ROLLBACK TO SAVEPOINT _rsync_setnn")
                            cursor.execute("RELEASE SAVEPOINT _rsync_setnn")
                        except Exception:
                            pass
                        break
                try:
                    cursor.execute("SAVEPOINT _rsync_identity")
                    cursor.execute(
                        f'ALTER TABLE "{schema}"."{name}" REPLICA IDENTITY USING INDEX "{idx}"'
                    )
                    cursor.execute("RELEASE SAVEPOINT _rsync_identity")
                except Exception:
                    # Older PG versions or non-superuser roles may refuse;
                    # log-and-continue keeps non-CDC destinations working. Scope to
                    # the SAVEPOINT so the column + index added above still persist.
                    try:
                        cursor.execute("ROLLBACK TO SAVEPOINT _rsync_identity")
                        cursor.execute("RELEASE SAVEPOINT _rsync_identity")
                    except Exception:
                        pass

            conn.commit()
            _curdb = getattr(getattr(conn, "info", None), "dbname", "?")
            logger.info("ensure_table: ensured %s.%s in db=%s", schema, name, _curdb)
            return {
                "success": True,
                "table": table,
                "schema": schema,
                "columns": safe_cols,
                "synthetic_pk": synthetic_pk_applied,
                "key_fields": safe_keys,
            }
        except Exception as e:
            if conn:
                try:
                    conn.rollback()
                except Exception:
                    pass
            return {"success": False, "error": str(e)}
        finally:
            if conn:
                try:
                    conn.close()
                except Exception:
                    pass

    def drop_table(self, params: Dict = None) -> Dict[str, Any]:
        """DROP destination table for run_mode=reload.

        Reload semantics are "rebuild from scratch": data + schema both
        regenerated from the latest source state. TRUNCATE is wrong
        here — it preserves the old column list, so:

          - columns the source has dropped stay around forever, full
            of stale data and creating type mismatches on re-INSERT;
          - column-type CHANGES (e.g. string -> json) silently keep
            the old type;
          - any manual schema drift outlives the source schema.

        DROP TABLE IF EXISTS ... CASCADE lets ensure_table recreate
        the destination fresh from the latest discover_schema, with
        the right columns and types. Matches DMS / Fivetran / Airbyte
        full-load semantics.

        Params:
            config:  Database connection config.
            table:   Destination table (optionally schema-qualified).
            cascade: bool, default true. Drops FK-dependent objects
                     (other tables, views) so reload doesn't fail when
                     this table is referenced elsewhere. Set false to
                     refuse the reload when FK deps exist.

        Returns ``{success, table, dropped: bool}``. Missing-table is
        reported as success-no-op (`dropped: false`) so the reload
        path is idempotent on first run.
        """
        params = params or {}
        config = self._get_config(params) if hasattr(self, "_get_config") else (params.get("config") or {})
        table = str(params.get("table") or "").strip()
        if not table:
            return {"success": False, "error": "Missing table"}

        schema, name = self._split_schema_table(table)
        # When the orchestrator passes a BARE (unqualified) table, it forwards
        # the destination schema separately as `namespace`. The executor sends a
        # bare table name on purpose so single-namespace dests (e.g. MySQL)
        # resolve their database from config — but for PostgreSQL the schema is
        # load-bearing: a bare name defaults to "public" here, so a reload of a
        # namespaced table (e.g. e2e_shopify_s4.products) would DROP the wrong
        # (non-existent) public.products, silently no-op, and leave the real
        # table — ghost rows survive the reload. Honor the namespace param when
        # the table spec itself carried no schema. Skip the literal "default":
        # that is the planner's generic fallback (not a real schema) and those
        # pipelines land in public, so public is the correct drop target.
        if "." not in str(table or ""):
            ns = str(params.get("namespace") or "").strip().strip('"').strip("`")
            if ns and ns.lower() != "default" and self._is_safe_ident(ns):
                schema = ns
        if not self._is_safe_ident(schema) or not self._is_safe_ident(name):
            return {"success": False, "error": f"Unsafe destination identifier: {schema}.{name}"}

        # cascade defaults to TRUE — matches DMS / Fivetran reload
        # semantics where dropping the destination is expected to
        # take dependents with it. Explicit false opts into strict
        # mode (DROP refuses to run if FK deps exist).
        cascade_clause = " CASCADE"
        if params.get("cascade") is False:
            cascade_clause = ""

        conn = None
        try:
            conn = self._get_connection(config)
            cursor = self._get_cursor(conn, as_dict=False)

            # Reload-mode ownership tracking (connection+namespace model).
            # The destination connection is already scoped by `config`, so
            # ownership is keyed on (this connection's database, namespace)
            # — the _rsync_pipelines ledger lives in this DB. We co-register
            # the reloading pipeline below but never refuse on a pipeline_id
            # mismatch: see the rationale at the registration site.
            # Backward-compat: when the orchestrator doesn't pass pipeline_id
            # (older builds) or _rsync_pipelines doesn't exist yet, skip and
            # fall through to existing behavior.
            pipeline_id = (
                params.get("pipeline_id")
                or (params.get("config") or {}).get("pipeline_id")
                or ""
            )
            pipeline_id = str(pipeline_id).strip()
            if pipeline_id and schema:
                try:
                    cursor.execute(
                        "SELECT to_regclass('public._rsync_pipelines')"
                    )
                    reg = cursor.fetchone()
                    has_table = bool(reg and reg[0])
                except Exception:
                    conn.rollback()
                    cursor = self._get_cursor(conn, as_dict=False)
                    has_table = False
                if has_table:
                    # Connection+namespace ownership, industry-aligned with
                    # Fivetran / Airbyte / DMS full-load semantics: a reload
                    # targeting a namespace on THIS connection is authorized
                    # to overwrite it regardless of which pipeline first
                    # registered it. Pipelines sharing a (connection,
                    # namespace) write the same physical tables, so either may
                    # rebuild them on reload. The previous pipeline_id-equality
                    # gate refused EVERY reload of a shared namespace (each
                    # pipeline saw the others' ledger rows) and silently
                    # dropped data. We now co-register the reloading pipeline
                    # so the ledger keeps an accurate owner set, then fall
                    # through to DROP.
                    cursor.execute(
                        "INSERT INTO public._rsync_pipelines "
                        "(pipeline_id, namespace) VALUES (%s, %s) "
                        "ON CONFLICT (pipeline_id) DO NOTHING",
                        (pipeline_id, schema),
                    )

            cursor.execute(
                "SELECT 1 FROM information_schema.tables "
                "WHERE table_schema = %s AND table_name = %s LIMIT 1",
                (schema, name),
            )
            existed = cursor.fetchone() is not None
            if not existed:
                conn.commit()
                return {"success": True, "table": table, "dropped": False, "message": "table does not exist"}

            cursor.execute(f'DROP TABLE IF EXISTS "{schema}"."{name}"{cascade_clause}')
            conn.commit()
            return {"success": True, "table": table, "dropped": True}
        except Exception as e:
            if conn:
                try:
                    conn.rollback()
                except Exception:
                    pass
            return {"success": False, "error": str(e)}
        finally:
            if conn:
                try:
                    conn.close()
                except Exception:
                    pass

    def upsert_data(self, params: Dict = None) -> Dict[str, Any]:
        """
        Upsert data into database (INSERT or UPDATE on conflict).
        Used by kafka-mcp-sink for CDC update events.

        Params:
            config: Database connection config
            table: Target table name
            data: List of records to upsert
            key_fields: Primary key columns for conflict detection
        """
        prepared = self.prepare_import_data(params)

        if not prepared.get('success', True):
            return prepared

        data = prepared.get('data', [])
        if not data:
            return {"success": True, "rows_upserted": 0}

        config = prepared['config']
        table = prepared.get('table')
        key_fields = (params or {}).get('key_fields') or (params or {}).get('primary_key_fields') or ['id']
        if isinstance(key_fields, str):
            key_fields = [key_fields]
        if not isinstance(key_fields, list) or len(key_fields) == 0:
            key_fields = ['id']

        # Synthetic-PK path. When the orchestrator detected that the
        # source declares no PKs, it sets ``synthetic_pk: true`` and
        # picks ``_rsync_row_hash`` as the conflict key. We compute the
        # hash from the source columns of each row here so PK-less
        # sources (raw REST, GraphQL without ID typing) still get
        # idempotent upserts without source-side cooperation.
        synthetic_pk = bool((params or {}).get("synthetic_pk"))
        if synthetic_pk:
            from datetime import datetime, timezone
            now_iso = datetime.now(timezone.utc).isoformat()
            # Determine the source columns once (every row has the same
            # schema after extraction); strip any synthetic carry-overs.
            source_cols = [c for c in data[0].keys() if not c.startswith("_rsync_")]
            for row in data:
                if SYNTHETIC_PK_COL not in row:
                    row[SYNTHETIC_PK_COL] = _compute_row_hash(row, source_cols)
                if SYNTHETIC_TS_COL not in row:
                    row[SYNTHETIC_TS_COL] = now_iso
            key_fields = [SYNTHETIC_PK_COL]

        if not table:
            return {"success": False, "error": "Target table not specified"}
        # PostgreSQL normalization is a no-op for other drivers. Pass params so a
        # bare table + per-pipeline namespace resolves to the right schema (the
        # insert/upsert/delete paths all share this so they stay consistent).
        table = self._normalize_table_for_postgresql(config, table, params)
        # Fail-closed write-path SQLi guard: the fallback INSERT/MERGE/DELETE
        # branches below interpolate the (tenant-controlled) destination table
        # raw. Reject an unsafe identifier before ANY raw {table} interpolation
        # — one entry guard covers every downstream branch (fast execute_values
        # path + per-row fallback) without re-quoting legit names.
        if self._safe_qualified_table(table) is None:
            return {"success": False, "error": f"Unsafe table identifier: {table!r}"}

        conn = None
        _conn_pooled = False
        _conn_broken = False
        try:
            conn, _conn_pooled = self._acquire_conn(config)
            pattern = self.driver_pattern

            # Handle NoSQL (MongoDB)
            if pattern.get("is_nosql"):
                return self._upsert_nosql(conn, config, table, data, key_fields)
            
            cursor = self._get_cursor(conn, as_dict=False)
            # Union keys across ALL rows, not just data[0]. Wide-format transforms
            # (json_flatten / array_expand) emit ragged rows — each record's flattened
            # key set differs — so deriving the column list from the first row alone
            # silently drops every column unique to later rows. All value binding below
            # (and in staged_upsert) uses row.get(col), so absent keys bind to NULL.
            columns = []
            _seen_cols = set()
            for _row in data:
                if not isinstance(_row, dict):
                    continue
                for _k in _row.keys():
                    if _k not in _seen_cols:
                        _seen_cols.add(_k)
                        columns.append(_k)
            rows_upserted = 0
            driver_module = pattern.get("module", "")

            # Per-column canonical types for type-aware value binding.
            col_types = (params or {}).get("column_types") or {}
            if not isinstance(col_types, dict):
                col_types = {}

            # Fast path: Postgres bulk stage-and-merge. Rows are batch-loaded
            # (execute_values) into an ON COMMIT DROP TEMP table, then merged
            # with a single INSERT ... SELECT ... ON CONFLICT DO UPDATE. This
            # collapses the one-network-round-trip-per-row cost of the loop
            # below (~91s for ~900 rows on remote Postgres) into a handful of
            # statements. On ANY failure — most importantly a missing target
            # table on a CDC first-write — we roll back and fall through to the
            # per-row loop, which auto-creates the table and binds each row
            # individually, so behavior is never regressed.
            is_pg = "psycopg2" in driver_module or "asyncpg" in driver_module
            if is_pg and self.supports_staged_load() and len(data) > 1:
                try:
                    written = self.staged_upsert(cursor, table, columns, data, key_fields, col_types)
                    # Record the Kafka high-water offset in the SAME transaction as
                    # the data so the destination DB is the single durable source of
                    # truth for CDC progress (replaces the Redis dedup ledger).
                    self._write_cdc_offsets(cursor, params)
                    conn.commit()
                    cursor.close()
                    return {"success": True, "rows_upserted": written}
                except Exception as stage_err:
                    logger.warning(
                        "upsert_data: staged path failed for target=%s, per-row fallback: %s",
                        table, stage_err,
                    )
                    self.log(f"staged upsert fell back to per-row loop: {stage_err}")
                    try:
                        conn.rollback()
                    except Exception:
                        pass
                    cursor = self._get_cursor(conn, as_dict=False)

            # Resolve the ON CONFLICT key ONCE before the loop — dest-PK-aware
            # (prefers the destination's real PRIMARY KEY over a surrogate that
            # would collide with a stale PK). Doing this per row would be one
            # catalog round-trip per row.
            perrow_conflict_keys = self._merge_conflict_keys(cursor, table, columns, key_fields)
            for row in data:
                if "psycopg2" in driver_module or "asyncpg" in driver_module:
                    # PostgreSQL: INSERT ... ON CONFLICT DO UPDATE.
                    # Quote identifiers (cols, conflict targets, EXCLUDED
                    # references) so case-sensitive column names like
                    # createdAt match what ensure_table() created — postgres
                    # folds unquoted idents to lowercase otherwise.
                    col_str = ", ".join([f'"{c}"' for c in columns])
                    placeholders = ", ".join(["%s"] * len(columns))
                    conflict_cols_list = perrow_conflict_keys
                    conflict_cols = ", ".join([f'"{c}"' for c in conflict_cols_list])
                    update_cols = [c for c in columns if c not in conflict_cols_list]

                    qualified = self._qualified_quoted_table(table)
                    if update_cols:
                        update_str = ", ".join([f'"{c}" = EXCLUDED."{c}"' for c in update_cols])
                        query = f"INSERT INTO {qualified} ({col_str}) VALUES ({placeholders}) ON CONFLICT ({conflict_cols}) DO UPDATE SET {update_str}"
                    else:
                        query = f"INSERT INTO {qualified} ({col_str}) VALUES ({placeholders}) ON CONFLICT ({conflict_cols}) DO NOTHING"
                    
                    values = tuple(_pg_bind_value(row.get(col), col_types.get(col)) for col in columns)
                    try:
                        cursor.execute(query, values)
                    except Exception as e:
                        # CDC streaming-only may target tables that don't exist yet.
                        # If this is a CDC write (kafka-mcp-sink sets cdc_metadata), try to auto-create and retry once.
                        msg = str(e)
                        is_cdc = isinstance(params, dict) and ("cdc_metadata" in params or "source_table" in params or "operation" in params)
                        if is_cdc and ("does not exist" in msg.lower() or "undefinedtable" in msg.lower()):
                            try:
                                conn.rollback()
                            except Exception:
                                pass
                            cursor = self._get_cursor(conn, as_dict=False)
                            self._ensure_table_for_cdc(cursor, table, columns, conflict_cols_list, col_types)
                            conn.commit()
                            cursor.execute(query, values)
                        else:
                            raise
                
                elif "mysql" in driver_module or "pymysql" in driver_module:
                    # MySQL: INSERT ... ON DUPLICATE KEY UPDATE
                    col_str = ", ".join(columns)
                    placeholders = ", ".join(["%s"] * len(columns))
                    update_cols = [c for c in columns if c not in key_fields]
                    
                    if update_cols:
                        update_str = ", ".join([f"{c} = VALUES({c})" for c in update_cols])
                        query = f"INSERT INTO {table} ({col_str}) VALUES ({placeholders}) ON DUPLICATE KEY UPDATE {update_str}"
                    else:
                        query = f"INSERT IGNORE INTO {table} ({col_str}) VALUES ({placeholders})"
                    
                    values = tuple(row.get(col) for col in columns)
                    cursor.execute(query, values)
                
                elif "oracledb" in driver_module or "cx_Oracle" in driver_module:
                    # Oracle: MERGE statement
                    col_str = ", ".join(columns)
                    src_cols = ", ".join([f":{i+1} AS {c}" for i, c in enumerate(columns)])
                    match_cond = " AND ".join([f"t.{k} = s.{k}" for k in key_fields])
                    update_cols = [c for c in columns if c not in key_fields]
                    
                    if update_cols:
                        update_str = ", ".join([f"t.{c} = s.{c}" for c in update_cols])
                        insert_cols = ", ".join([f"s.{c}" for c in columns])
                        query = f"""
                            MERGE INTO {table} t
                            USING (SELECT {src_cols} FROM dual) s
                            ON ({match_cond})
                            WHEN MATCHED THEN UPDATE SET {update_str}
                            WHEN NOT MATCHED THEN INSERT ({col_str}) VALUES ({insert_cols})
                        """
                    else:
                        insert_cols = ", ".join([f"s.{c}" for c in columns])
                        query = f"""
                            MERGE INTO {table} t
                            USING (SELECT {src_cols} FROM dual) s
                            ON ({match_cond})
                            WHEN NOT MATCHED THEN INSERT ({col_str}) VALUES ({insert_cols})
                        """
                    
                    values = tuple(row.get(col) for col in columns)
                    cursor.execute(query, values)
                
                else:
                    # Generic fallback: DELETE + INSERT
                    # Cast both sides to text to handle type mismatches (e.g. INT PK in a TEXT column).
                    where_clause = " AND ".join([f"{k}::text = %s::text" for k in key_fields])
                    key_values = tuple(str(row.get(k)) if row.get(k) is not None else None for k in key_fields)
                    cursor.execute(f"DELETE FROM {table} WHERE {where_clause}", key_values)
                    
                    col_str = ", ".join(columns)
                    placeholders = ", ".join(["%s"] * len(columns))
                    values = tuple(row.get(col) for col in columns)
                    cursor.execute(f"INSERT INTO {table} ({col_str}) VALUES ({placeholders})", values)
                
                rows_upserted += 1

            # Record the Kafka high-water offset in the SAME transaction as the
            # data (see _write_cdc_offsets) so data + offset commit atomically.
            self._write_cdc_offsets(cursor, params)
            conn.commit()
            cursor.close()
            return {"success": True, "rows_upserted": rows_upserted}

        except Exception as e:
            _conn_broken = True
            if conn:
                try:
                    conn.rollback()
                except:
                    pass
            return {"success": False, "error": str(e)}
        finally:
            self._release_conn(conn, _conn_pooled, config, broken=_conn_broken)
    
    # =========================================================================
    # DESTINATION LOAD HOOKS — Postgres stage-and-merge (DestinationLoadMixin)
    # =========================================================================
    # These back the fast path in upsert_data(). They run on a caller-supplied
    # cursor inside the caller's transaction; the caller owns commit/rollback.

    def _stage_create(self, cursor, target_table: str, columns: List[str]) -> str:
        """Create an ON COMMIT DROP TEMP table mirroring the target's columns.

        ``LIKE {target} INCLUDING DEFAULTS`` copies exact column types so the
        bulk load binds and the subsequent INSERT...SELECT merge see identical
        types. Raises if the target doesn't exist yet (CDC first-write); the
        caller then falls back to the per-row path which auto-creates it.
        """
        import uuid
        staging = f'"_rsync_stage_{uuid.uuid4().hex[:12]}"'
        cursor.execute(
            f'CREATE TEMP TABLE {staging} '
            f'(LIKE {self._qualified_quoted_table(target_table)} INCLUDING DEFAULTS) ON COMMIT DROP'
        )
        return staging

    def _stage_bulk_load(self, cursor, staging_table: str, columns: List[str],
                         rows: List[Dict[str, Any]], col_types: Dict[str, Any]) -> None:
        """Bulk-load rows into the staging table (which the merge step then
        reconciles into the target via ON CONFLICT, so the final table keeps
        one row per key).

        Default path: psycopg2 ``execute_values`` (multi-row INSERT, paged).
        When ``RSYNC_PG_BULK_COPY`` is enabled: ``COPY ... FROM STDIN`` into the
        staging temp — far faster for large CDC flushes. Both reuse the same
        ``_pg_bind_value`` coercion (COPY via ``_build_pg_copy_csv``), so JSON /
        NULL / case handling is byte-for-byte identical; only the load
        transport differs. The downstream ``_stage_merge`` is untouched.
        """
        col_str = ", ".join([f'"{c}"' for c in columns])
        if self._pg_bulk_copy_enabled():
            buf = io.StringIO(_build_pg_copy_csv(rows, columns, col_types))
            cursor.copy_expert(
                f'COPY {staging_table} ({col_str}) FROM STDIN WITH (FORMAT csv)',
                buf,
            )
            logger.info(
                "[bulk_copy] staged_upsert COPY -> staging temp (%d rows)",
                len(rows),
            )
            return
        from psycopg2.extras import execute_values
        template = "(" + ", ".join(["%s"] * len(columns)) + ")"
        values = [
            [_pg_bind_value(row.get(col), col_types.get(col)) for col in columns]
            for row in rows
        ]
        execute_values(
            cursor,
            f'INSERT INTO {staging_table} ({col_str}) VALUES %s',
            values,
            template=template,
            page_size=1000,
        )

    def _stage_merge(self, cursor, target_table: str, staging_table: str,
                     columns: List[str], key_fields: List[str], merge_method: str) -> None:
        """Merge staged rows into the target via INSERT ... SELECT ... ON
        CONFLICT DO UPDATE — the set-based equivalent of the per-row upsert,
        with identical quoted-identifier and EXCLUDED-update semantics."""
        col_str = ", ".join([f'"{c}"' for c in columns])
        conflict_cols_list = [k for k in key_fields if k in columns]
        if not conflict_cols_list:
            conflict_cols_list = ["id"] if "id" in columns else [columns[0]]
        conflict_cols = ", ".join([f'"{c}"' for c in conflict_cols_list])
        update_cols = [c for c in columns if c not in conflict_cols_list]
        merge_sql = (
            f'INSERT INTO {self._qualified_quoted_table(target_table)} ({col_str}) '
            f'SELECT {col_str} FROM {staging_table} '
            f'ON CONFLICT ({conflict_cols}) '
        )
        if update_cols:
            update_str = ", ".join([f'"{c}" = EXCLUDED."{c}"' for c in update_cols])
            merge_sql += f'DO UPDATE SET {update_str}'
        else:
            merge_sql += 'DO NOTHING'
        cursor.execute(merge_sql)

    def _stage_drop(self, cursor, staging_table: str) -> None:
        """Drop the staging table eagerly. It is ON COMMIT DROP, but dropping it
        now keeps the name free if a same-transaction retry ever reuses it."""
        try:
            cursor.execute(f'DROP TABLE IF EXISTS {staging_table}')
        except Exception:
            pass

    def _pg_bulk_copy_enabled(self, params: Dict = None) -> bool:
        """Gate the COPY import path. Default-off: unless ``RSYNC_PG_BULK_COPY``
        is truthy (or the caller passes ``bulk_copy=True``), the byte-identical
        paged ``executemany`` path runs. Lets the fast path ship and soak with
        zero change to the default runtime behavior."""
        p = params or {}
        if "bulk_copy" in p:
            return bool(p.get("bulk_copy"))
        return str(os.environ.get("RSYNC_PG_BULK_COPY", "")).strip().lower() in (
            "1", "true", "yes", "on"
        )

    def _copy_import_rows(self, cursor, table: str, columns: List[str],
                          data: List[Dict[str, Any]],
                          col_types: Dict[str, Any]) -> int:
        """Append-only bulk load via ``COPY ... FROM STDIN`` (CSV), straight
        into the target table. ``import_data`` is INSERT-only so no staging or
        merge is required. Chunked to bound peak memory (``copy_expert`` buffers
        each chunk in the driver). Returns rows loaded (``cursor.rowcount``),
        preserving the submitted-vs-affected silent-data-loss guard. Runs on the
        caller's cursor/transaction so the data + ``_write_cdc_offsets`` write
        still commit atomically."""
        col_str = ", ".join([f'"{c}"' for c in columns])
        copy_sql = (
            f"COPY {self._qualified_quoted_table(table)} ({col_str}) "
            f"FROM STDIN WITH (FORMAT csv)"
        )
        chunk = max(1, int(getattr(self, "_copy_chunk_rows", 50_000)))
        rows_loaded = 0
        for i in range(0, len(data), chunk):
            part = data[i:i + chunk]
            buf = io.StringIO(_build_pg_copy_csv(part, columns, col_types))
            cursor.copy_expert(copy_sql, buf)
            affected = cursor.rowcount
            rows_loaded += affected if (affected is not None and affected >= 0) else len(part)
        logger.info(
            "[bulk_copy] import_data COPY -> %s (%d rows loaded)",
            table, rows_loaded,
        )
        return rows_loaded

    def delete_data(self, params: Dict = None) -> Dict[str, Any]:
        """
        Delete data from database by primary key.
        Used by kafka-mcp-sink for CDC delete events.
        
        Params:
            config: Database connection config
            table: Target table name
            data: List of records containing key fields
            key_fields: Primary key columns
        """
        params = params or {}

        # Normalize common CDC delete shapes: some producers send the PK in `key_data`,
        # or embed the pre-image under `before` (Debezium).
        normalized = params
        if isinstance(normalized, dict):
            d = normalized.get("data")
            if d is None:
                for k in ("key_data", "before", "key", "kafka_key", "record_key", "primary_key", "keys"):
                    if isinstance(normalized.get(k), dict):
                        normalized = {**normalized, "data": [normalized.get(k)]}
                        break
                if normalized.get("data") is None and isinstance(normalized.get("keys"), list):
                    normalized = {**normalized, "data": normalized.get("keys")}
            elif isinstance(d, dict):
                normalized = {**normalized, "data": [d]}

        prepared = self.prepare_import_data(normalized)
        if not prepared.get('success', True):
            return prepared

        config = prepared.get('config') or {}
        table = prepared.get('table')
        data = prepared.get('data', []) or []

        key_fields = params.get('key_fields') or params.get('primary_key_fields') or config.get('key_fields') or ['id']
        if isinstance(key_fields, str):
            key_fields = [key_fields]
        if not isinstance(key_fields, list) or len(key_fields) == 0:
            key_fields = ['id']
        
        if not table:
            return {"success": False, "error": "Target table not specified"}
        # PostgreSQL normalization is a no-op for other drivers. Pass params so a
        # bare table + per-pipeline namespace resolves to the right schema (the
        # insert/upsert/delete paths all share this so they stay consistent).
        table = self._normalize_table_for_postgresql(config, table, params)
        # Fail-closed write-path SQLi guard: reject an unsafe (tenant-controlled)
        # destination table before it reaches _qualified_quoted_table / raw
        # {table} interpolation. Mirrors the read-path (export) guard.
        if self._safe_qualified_table(table) is None:
            return {"success": False, "error": f"Unsafe table identifier: {table!r}"}

        if not data:
            return {"success": True, "rows_deleted": 0}
        
        conn = None
        try:
            conn = self._get_connection(config)
            pattern = self.driver_pattern
            
            if pattern.get("is_nosql"):
                return self._delete_nosql(conn, config, table, data, key_fields)
            
            cursor = self._get_cursor(conn, as_dict=False)
            rows_deleted = 0

            if not key_fields:
                # No keys → a WHERE-less DELETE would wipe the whole table. Refuse.
                raise ValueError(f"delete_data: no key_fields provided for {table}; refusing unkeyed delete")

            for row in data:
                # The WHERE clause and the bind tuple MUST be built over the SAME
                # set of columns. The old code built the clause over ALL key_fields
                # but filtered the tuple to only keys present in the row — a mismatch
                # that either raised a bind-count error or, when all keys were absent,
                # silently skipped the DELETE (`if key_values:` on an empty tuple) and
                # left an orphan row. Fail loud instead: a delete event that lacks its
                # key columns is a data-integrity problem the caller must see (it will
                # roll back and route to the DLQ).
                missing = [k for k in key_fields if k not in row]
                if missing:
                    raise ValueError(
                        f"delete_data: row missing key field(s) {missing} for {table}; "
                        f"cannot build a safe WHERE clause"
                    )

                # Cast both sides to text to handle type mismatches (e.g. INT PK in a TEXT column).
                # Quote the key-column identifiers so case-sensitive PKs match the
                # case-preserved columns ensure_table() created (same reason the
                # table identifier is quoted below).
                where_clause = " AND ".join([f'"{k}"::text = %s::text' for k in key_fields])
                key_values = tuple(str(row.get(k)) if row.get(k) is not None else None for k in key_fields)

                cursor.execute(f"DELETE FROM {self._qualified_quoted_table(table)} WHERE {where_clause}", key_values)
                rows_deleted += cursor.rowcount if hasattr(cursor, 'rowcount') else 1

            # Record the Kafka high-water offset in the SAME transaction as the
            # delete so progress + data stay atomic (replaces Redis dedup).
            self._write_cdc_offsets(cursor, params)
            conn.commit()
            cursor.close()
            return {"success": True, "rows_deleted": rows_deleted}
        
        except Exception as e:
            if conn:
                try:
                    conn.rollback()
                except:
                    pass
            return {"success": False, "error": str(e)}
        finally:
            if conn:
                try:
                    conn.close()
                except:
                    pass
    
