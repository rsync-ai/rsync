def _pg_pool_key(config: Dict) -> str:
    """Bucket key for the idle-connection cache: a digest of the WHOLE config.

    This used to be ``"|".join(...)`` over ("host", "port", "database", "user")
    only. The password was therefore NOT part of the key, so two configs that
    differed solely in credentials shared a bucket, and _acquire_conn handed
    one config's authenticated connection to the other. Nothing caught it:
    _conn_is_live runs ``SELECT 1``, which proves the socket works, not that
    the caller's credentials do. Consequences, worst first: a rotated password
    or a REVOKEd role kept writing (upsert_data, the only pooled path, is the
    WRITE); and the destination-failure chaos test was silently disarmed
    because its only fault lever — a wrong password — stopped producing a
    fault. See KI-PGMCP-POOL-KEY-OMITS-PASSWORD in CAPABILITIES.md.

    Hashing the entire config is deliberately over-inclusive, and that
    asymmetry is the whole point: an extra key can only cause a pool MISS
    (open a fresh connection — correct, merely slower), while a missing key
    causes a wrong-credential HIT. Enumerating "the fields that matter" is
    what produced this bug, and re-enumerating them would only move it to the
    next field added. Reuse within a worker is unaffected: the sink sends the
    same stable ``DestinationConfig`` map on every flush, which is where the
    pool's throughput win actually comes from.

    The digest is only ever a dict key — never logged, returned, or surfaced
    (grep: _acquire_conn/_release_conn are its sole consumers) — so hashing a
    credential into it does not create a new exposure path.
    """
    c = config or {}
    try:
        canon = json.dumps(c, sort_keys=True, separators=(",", ":"), default=str)
    except Exception:
        # Never let an exotic value break pooling: fall back to a stable
        # repr. Worst case this is a coarser key, which is a MISS, not a
        # wrong hit.
        canon = repr(sorted((str(k), str(v)) for k, v in c.items()))
    return hashlib.sha256(canon.encode("utf-8")).hexdigest()


