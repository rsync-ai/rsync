    def export(self, params: Dict) -> Dict[str, Any]:
        """
        Export data from the source.
        REQUIRED by BaseMCPConnector abstract class.
        """
        # Delegate to ApiHandler (contract-driven)
        prepared = self.prepare_export_data(params)
        if not prepared.get('success'):
            return prepared
        
        config = prepared['config']
        
        resource_endpoints = {
            "databases": "/databases",
            "users": "/users",
            "pages": "/search",
            "blocks": "/blocks",
        }

        # Determine which resource/object to export.
        # If not provided, default to the first known resource so the connector is usable
        # out-of-the-box (and offline QA can run without guessing an object name).
        # NOTE: The orchestrator/executor and BaseMCPConnector may normalize generic terms like
        # 'table' into API-ish terms like 'endpoint'. Treat these as aliases so pipelines work
        # without per-connector manual fixes.
        resource = (
            params.get('object')
            or params.get('resource')
            or params.get('endpoint')  # common normalization target for api_saas
            or params.get('table')
        )
        if not resource:
            if resource_endpoints:
                resource = next(iter(resource_endpoints.keys()))
            else:
                return {"success": False, "error": "Missing 'object' parameter"}

        # Strip schema prefix if the orchestrator passed a qualified name like
        # "stripe.charges" — endpoint map keys are bare resource names. Parallels
        # the GraphQL template's rsplit dispatch fix (F-13, PR #61).
        if isinstance(resource, str) and "." in resource:
            resource = resource.rsplit(".", 1)[-1]

        endpoint = resource_endpoints.get(resource)
        if not endpoint:
            return {"success": False, "error": f"Unknown resource: {resource}"}
        
        # Extract pagination parameters
        max_pages = int(params.get("max_pages") or DEFAULT_MAX_PAGES)
        max_records = int(params.get("max_records") or DEFAULT_MAX_RECORDS)
        
        # Extract incremental sync parameters
        since = params.get('since') or params.get('updated_since') or params.get('modified_after')
        cursor = params.get('cursor') or params.get('next_cursor')
        incremental_field = params.get('incremental_field', 'updated_at')
        
        # Only pass *query params* to the API (exclude config/object/max_pages, etc.)
        query_params = {}
        if isinstance(params, dict):
            qp = params.get("params")
            if isinstance(qp, dict):
                query_params = qp
        
        # Build resource config with incremental metadata
        resource_config = self._get_resource_config(resource)
        
        # Always forward 'since' to the API when provided — even if the resource
        # doesn't advertise supports_incremental, sending the param is harmless
        # (the API will ignore it), and NOT sending it silently drops the caller's
        # watermark filter, causing a full re-sync every time.
        if since:
            incremental_param = resource_config.get('incremental_param', 'updated_since')
            query_params[incremental_param] = since
        
        # Apply cursor for pagination resumption
        if cursor:
            pagination_param = resource_config.get('pagination_param', 'cursor')
            query_params[pagination_param] = cursor

        # On an incremental re-run the caller passes its last checkpoint as
        # `since`. Forward it as prior_watermark so a 0-row result echoes the
        # checkpoint back instead of resetting it (and re-scanning from zero).
        prior_watermark = None
        if since and resource_config.get('supports_incremental'):
            prior_watermark = {"field": incremental_field, "value": since}

        try:
            # Use ApiHandler for export, passing per-resource pagination/shape config
            # so PaginationHandler uses the correct settings for this resource instead
            # of the connector-wide defaults (critical for multi-resource connectors).
            result = self._api_handler.export_resource(
                connector=self,
                config=config,
                resource=resource,
                endpoint=endpoint,
                params=query_params,
                max_pages=max_pages,
                max_records=max_records,
                incremental_field=incremental_field if resource_config.get('supports_incremental') else None,
                resource_config=resource_config,
                prior_watermark=prior_watermark,
            )

            # Convert ExportResult to dict (carries records, next_cursor,
            # has_more, and stats.watermark/max_watermark).
            return result.to_dict()

        except Exception as e:
            logger.error(f"Export failed: {e}", exc_info=True)
            return {"success": False, "error": str(e)}
    
