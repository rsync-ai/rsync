    # Credential-bearing config keys, used to build an anonymous control probe.
    # Covers the per-connector config key names; the instance-side credential
    # surface is the one BaseMCPConnector enumerates in _CONNECTION_STATE_FIELDS.
    _CREDENTIAL_CONFIG_KEYS = (
        "access_token", "token", "api_key", "apikey", "key", "secret",
        "client_secret", "client_id", "password", "username", "bearer_token",
        "personal_access_token", "private_token", "auth_token",
    )
    _AUTH_HEADER_NAMES = (
        "authorization", "x-api-key", "api-key", "x-auth-token",
        "private-token", "x-access-token",
    )

    def _credentials_present(self, config: Dict) -> bool:
        """True if the caller supplied a credential that still has to be proven.

        Checks this connector's OWN declared auth config_keys first. A hardcoded
        list of common names misses vendor-specific ones -- Notion calls its
        token `integration_token` -- and a credential we fail to notice here is
        a credential that is then never validated at all.
        """
        cfg = config or {}
        for spec in (getattr(self, "SUPPORTED_AUTH_METHODS", None) or {}).values():
            for k in (spec.get("config_keys") or []):
                if cfg.get(k):
                    return True
            if spec.get("query_param") and cfg.get(spec["query_param"]):
                return True
        if cfg.get("username") and cfg.get("password"):
            return True
        return any(cfg.get(k) for k in (
            "access_token", "token", "api_key", "apikey", "bearer_token",
            "personal_access_token", "private_token", "auth_token",
        ))

    def _anonymous_config(self, config: Dict) -> Dict:
        """Copy of `config` with every credential-bearing key removed.

        Prefers this connector's OWN declared auth config_keys, so a
        vendor-specific key name (Notion calls its token `integration_token`)
        is stripped as well; the static list below only fills the gap for
        connectors that declare no auth methods.
        """
        keys = set(self._CREDENTIAL_CONFIG_KEYS)
        for spec in (getattr(self, "SUPPORTED_AUTH_METHODS", None) or {}).values():
            for k in (spec.get("config_keys") or []):
                keys.add(str(k).lower())
            if spec.get("query_param"):
                keys.add(str(spec["query_param"]).lower())
        return {k: v for k, v in (config or {}).items() if k.lower() not in keys}

    def _probe_endpoint_is_public(self, endpoint: str, config: Dict,
                                  params: Dict = None) -> Optional[bool]:
        """Re-issue a successful probe WITHOUT credentials, as a control.

        A 2xx only proves the credentials are valid if the endpoint would have
        REFUSED an anonymous caller. So ask it that question directly:

            True  -> answered 2xx anonymously too: the endpoint is PUBLIC, and
                     the authenticated 2xx proves nothing about the credentials.
            False -> rejected the anonymous request: it IS auth-protected, so
                     the credentials earned the 2xx and are proven valid.
            None  -> inconclusive; the caller must fall back to legacy behaviour.

        Credentials reach a request from three places -- the config dict, an
        env-var fallback, and instance state cached by
        configure_from_connection() -- so all three are neutralised here. The
        two header sets are then diffed to CONFIRM the strip actually worked: if
        the "anonymous" request would still carry auth, its answer is
        meaningless, so return None rather than a confidently wrong verdict.
        """
        anon = self._anonymous_config(config)
        saved_env = {k: os.environ.get(k) for k in ("ALLOW_ENV_CREDENTIALS", "MCP_API_KEY")}
        saved_api_key = getattr(self, "api_key", None)
        saved_oauth = getattr(self, "_oauth_token", None)
        try:
            os.environ["ALLOW_ENV_CREDENTIALS"] = "false"
            os.environ.pop("MCP_API_KEY", None)
            self.api_key = ""
            self._oauth_token = None
            try:
                authed_headers = self._get_headers(config) or {}
                anon_headers = self._get_headers(anon) or {}
            except Exception:
                return None

            def _auth_material(headers):
                out = {}
                for k, v in headers.items():
                    if k.lower() not in self._AUTH_HEADER_NAMES:
                        continue
                    # A credential-free header is not auth material: an empty
                    # token renders as a bare scheme name ("Bearer"), which a
                    # server treats exactly like sending nothing at all.
                    parts = str(v or "").split()
                    if not parts:
                        continue
                    if len(parts) == 1 and parts[0].lower() in ("bearer", "token", "basic"):
                        continue
                    out[k.lower()] = v
                return out

            # Nothing to strip, or the strip changed nothing (query-string auth,
            # an unknown config key, a cached token we cannot see). Either way an
            # anonymous 2xx would be indistinguishable from an authenticated one.
            if not _auth_material(authed_headers):
                return None
            if _auth_material(anon_headers) == _auth_material(authed_headers):
                return None
            try:
                result = self._make_request('GET', endpoint, anon, params=params)
            except Exception:
                return None
        finally:
            for _k, _v in saved_env.items():
                if _v is None:
                    os.environ.pop(_k, None)
                else:
                    os.environ[_k] = _v
            if saved_api_key is not None:
                self.api_key = saved_api_key
            self._oauth_token = saved_oauth

        if result.get("success"):
            return True
        if int(result.get("status_code") or 0) in (401, 403):
            return False
        return None

    def test_connection(self, params: Dict = None) -> Dict[str, Any]:
        """Test connectivity to Notion."""
        config = self._get_config(params)
        
        try:
            # Test API connectivity with an auth-protected probe (T1-8).
            #
            # FALLBACK probes: generic "whoami"-shaped paths. They are tried
            # LAST, not first — `probes` below is resource_candidates + these,
            # in that order, because these paths exist on few APIs.
            #
            # A 2xx here does NOT by itself prove the credentials are valid.
            # The rule this replaced trusted one unconditionally, on the
            # convention that a whoami path always REQUIRES auth and answers
            # 401/403 without it; that convention is not universal (github-rest
            # probes "/user" ahead of "/users/me" because the latter is an
            # ordinary public lookup on GitHub). So when a credential was
            # supplied, a whoami 2xx is put to the SAME
            # _probe_endpoint_is_public control as any other probe.
            # Driven, not inferred: with every resource endpoint 404 and a
            # whoami answering 2xx to authenticated AND anonymous callers, this
            # connector returns `credentials_validated: False` plus a warning.
            # Two-sided — the same world with that whoami refusing anonymous
            # callers (401) returns `credentials_validated: True`. A whoami 2xx
            # is still trusted uncorroborated in exactly one case: where that
            # control cannot reach a verdict. The paragraph below says when.
            whoami_candidates = [
                "/users/me",
                "/user/me",
                "/me",
                "/whoami",
                "/account",
                "/accounts/me",
                "/profile",
            ]
            # PRIMARY probes (the ones actually tried first) are THIS
            # connector's own spec-declared,
            # list-able, path-param-free resource endpoints. They let a
            # vendor that exposes NO whoami endpoint (e.g. petstore:
            # /store/inventory) still be reachability-tested. We NEVER
            # probe bare "/".
            #
            # SECURITY (T1-8): a 2xx on a resource endpoint does NOT, by
            # itself, prove the credentials are valid — the endpoint may be
            # coincidentally PUBLIC while the rest of the API needs auth, so
            # an invalid-credentials connection could otherwise pass here and
            # wrongly auto-promote draft->preview. We therefore accept a bare
            # 2xx as success ONLY when there is no credential to validate —
            # `allow_unauth_pass = not creds_present` below. `auth_type` does
            # NOT take part in that decision; see the note on it below.
            #
            # When a credential WAS supplied, every 2xx is put to a control:
            # _probe_endpoint_is_public re-issues the SAME request with the
            # credential stripped. The control only decides when it can strip
            # something AND read the answer; otherwise it returns None and the
            # older, weaker rule decides instead — a whoami 2xx is then
            # trusted with nothing corroborating it, a resource 2xx is not.
            # None is reachable in ordinary configs, not just in theory: when
            # _get_headers() puts no auth material on the request, or stripping
            # the credential does not change the headers, the control returns
            # WITHOUT issuing a second request at all. That is the state
            # whenever _credentials_present() says yes — it ends in a generic
            # key list — but _get_headers() never turns that key into a
            # header: a config carrying `personal_access_token` against a
            # connector that does not declare that key does exactly this. So
            # `credentials_validated: True` can still rest on an uncorroborated
            # whoami 2xx. The fallback is deliberate — an inconclusive control
            # must not fail an otherwise good connection — but the hole it
            # leaves is open, and is NOT closed here.
            resource_candidates = [
                "/databases",
                "/users",
                "/search",
                "/blocks",
            ]

            creds_present = self._credentials_present(config)
            # `auth_type` here is PLUMBING, not semantics. Connectors set it to
            # "none" on purpose so BaseMCPConnector does not auto-inject its own
            # Authorization header (see __init__), and every generated API-key
            # REST connector does the same. Keying the guard below on
            # auth_type == "none" therefore DISABLED it on exactly the
            # connectors that needed it, and left it armed only on connectors
            # that genuinely have no auth to check. The only thing that matters
            # here is whether the caller handed us a credential still to prove.
            allow_unauth_pass = not creds_present

            last_err = None
            saw_auth_failure = False
            saw_public_endpoint = False
            # Probe THIS connector's own listable, path-param-free resource
            # endpoints FIRST (with a minimal page) via the real auth path — for
            # the vast majority of vendors these are the only endpoints that
            # actually exist. Fall back to the generic whoami candidates only as
            # a LAST resort (they exist on few APIs).
            probes = (
                [(ep, True) for ep in resource_candidates if ep]
                + [(ep, False) for ep in whoami_candidates]
            )
            for ep, is_resource in probes:
                try:
                    # Resource probes hit a real list collection — request only a
                    # minimal page so the reachability check is cheap. whoami
                    # probes take no page param.
                    probe_params = {"limit": 1} if is_resource else None
                    result = self._make_request('GET', ep, config, params=probe_params)
                except Exception as e:
                    last_err = str(e)
                    continue
                if result.get("success"):
                    if allow_unauth_pass:
                        # No credentials were supplied, so there is nothing to
                        # validate and reachability is the whole question.
                        return {
                            "success": True,
                            "message": "Connection successful",
                            "credentials_validated": False,
                        }
                    # Credentials WERE supplied, so a 2xx only proves them valid
                    # if this endpoint would have refused an anonymous caller.
                    # That has to be asked of a whoami path too, not assumed:
                    # several vendors serve one publicly (GitHub answers
                    # /users/me to anybody), which is exactly how an unvalidated
                    # credential used to be reported as a good connection.
                    verdict = self._probe_endpoint_is_public(ep, config, params=probe_params)
                    if verdict is False:
                        # It refused the anonymous caller, so the 2xx we got was
                        # earned by the credentials. That is proof.
                        return {
                            "success": True,
                            "message": "Connection successful",
                            "credentials_validated": True,
                        }
                    if verdict is True:
                        # Proven public: answers everyone identically, so it can
                        # neither confirm nor deny the credentials. Remember that
                        # and keep looking for a stronger probe.
                        saw_public_endpoint = True
                        last_err = "reachable, but the endpoints that answered are public and cannot validate credentials"
                        continue
                    # Inconclusive (no control possible) -- fall back to the
                    # historical rule: trust a whoami 2xx, keep looking after a
                    # resource 2xx.
                    if not is_resource:
                        return {
                            "success": True,
                            "message": "Connection successful",
                            "credentials_validated": True,
                        }
                    last_err = "reachable but credentials were not validated on an auth-protected endpoint"
                    continue
                code = int(result.get("status_code") or 0)
                if code in (401, 403):
                    # Auth header was received and rejected. Don't keep
                    # trying — credentials are invalid.
                    saw_auth_failure = True
                    last_err = result.get("error") or f"HTTP {code}: authentication failed"
                    break
                # Any other non-2xx (400/404/5xx/network): this endpoint is
                # not a usable probe on this vendor. Record it and try the
                # next candidate rather than giving up early on one bad
                # endpoint.
                last_err = result.get("error") or f"HTTP {code}"
                continue

            # If we tried every probe and none confirmed the connection,
            # the connection is either misconfigured (auth wrong) or the
            # vendor uses a non-standard auth-protected probe path.
            # Either way: REFUSE to report success — unless AT LEAST ONE
            # endpoint that answered was proven public. `saw_public_endpoint`
            # is set by any SINGLE verdict-True probe, not by all of them, so
            # an endpoint that answered 2xx and never reached a verdict does
            # not stop the branch below from firing.
            #
            # There is no probe-path config key anywhere in this repo. Both
            # candidate lists come from the generator — whoami_candidates is a
            # literal in connector.py.j2, resource_candidates is emitted from
            # the spec's listable, path-param-free resources — so widening the
            # probe set means changing the template or the spec and
            # regenerating. Editing the list inside a generated connector.py is
            # reverted by the next regeneration.
            if saw_auth_failure:
                return {"success": False, "error": last_err}
            if saw_public_endpoint:
                # We reached the API and PROVED, by re-running a probe with the
                # credentials stripped, that AT LEAST ONE endpoint that answered
                # serves anonymous callers identically. Nothing proved a credential
                # — that path returns above — so refusing here would make a
                # genuinely public API impossible to add at all. Report it usable
                # and state plainly what was not checked.
                #
                # `credentials_validated` GATES NOTHING, and neither it nor the
                # `warning` below survives the trip out of this process.
                # Checked, not assumed: `credentials_validated` appears in no
                # .go/.ts/.tsx file in the repo; the orchestrator's
                # executor.Agent.TestConnection collapses this whole dict to a
                # (bool, string) built only from resp.Success; the api-gateway's
                # performConnectionTest then decodes success/error/message and
                # nothing else, so `warning` is dropped as well. What actually
                # promotes draft->preview is the SIBLING key `success`: it
                # becomes connections.last_test_status='success', which
                # computeLifecycle (api-gateway tools.go) counts — and
                # assessor/connector.go renders the same bool as "Connected and
                # authenticated ... credentials are valid", the qualification
                # already gone. Keep these keys honest, but do not describe
                # them as a gate.
                # KNOWN WORDING BUG, left in place on purpose: the warning text
                # below says "every probe endpoint that responded", which claims
                # more than was established — one proven-public endpoint reaches
                # this branch, and another may have answered 2xx without ever
                # reaching a verdict. Rewording a returned string is a behaviour
                # change, so it is filed in BACKLOG.md rather than done here.
                return {
                    "success": True,
                    "message": "Connection successful",
                    "credentials_validated": False,
                    "warning": (
                        "Reachable, but the credentials could not be validated: every probe "
                        "endpoint that responded also responds without credentials. Calls to "
                        "auth-protected paths on this API may still fail."
                    ),
                }
            return {
                "success": False,
                "error": f"No probe endpoint confirmed the connection. Last error: {last_err or 'all candidates 404/timed out'}.",
            }
        except Exception as e:
            return {"success": False, "error": str(e)}
    
