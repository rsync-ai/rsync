    def import_data(self, params: Dict) -> Dict[str, Any]:
        """
        Import data to the destination.
        REQUIRED by BaseMCPConnector abstract class.
        """
        # Use generic helper for staging retrieval and normalization
        prepared = self.prepare_import_data(params)
        
        if not prepared.get('success', True):
            return prepared
        
        data = prepared.get('data', [])
        if not data:
            return {"success": True, "rows_inserted": 0, "message": "No data to import"}
        
        config = prepared['config']
        obj_name = params.get('object') or params.get('table')

        if not obj_name:
            return {"success": False, "error": "Target object not specified"}
        # Strip schema prefix (e.g. "stripe.charges" → "charges") — parallels F-13.
        if isinstance(obj_name, str) and "." in obj_name:
            obj_name = obj_name.rsplit(".", 1)[-1]

        # Per-pipeline target namespace travels separately from the row data.
        # SaaS endpoints are fixed per resource so there is nothing to qualify;
        # capture it (skipping the planner's "default" placeholder) rather than
        # silently dropping it.
        namespace = str((params or {}).get('namespace') or (params or {}).get('db_or_schema') or "").strip()
        if namespace == "default":
            namespace = ""

        # Find resource endpoint. F13 — only resources that declare a create
        # verb (POST) are valid append targets; a read-only resource (no
        # create/update/delete) is never offered so a load never 405s per record.
        resource_endpoints = {
            "customers": "/customers",
            "products": "/products",
        }

        endpoint = resource_endpoints.get(obj_name)
        if not endpoint:
            return {"success": False, "error": f"Resource {obj_name!r} is not writable (no create capability)"}

        # Append (POST per record). For idempotent loads use upsert_data, which
        # PUTs on the row id so re-runs don't duplicate.
        try:
            inserted = 0
            errors = []

            for record in data:
                result = self._make_request('POST', endpoint, config, data=record)
                if result.get('success'):
                    inserted += 1
                else:
                    errors.append(result.get('error', 'Unknown error'))

            return {
                "success": len(errors) == 0,
                "rows_inserted": inserted,
                "errors": errors[:10] if errors else []  # Limit error list
            }
        except Exception as e:
            return {"success": False, "error": str(e)}
    
    
    def upsert_data(self, params: Dict = None) -> Dict[str, Any]:
        """Idempotently upsert records into a REST resource (PUT on id, POST on miss)"""
        # Use generic helper for staging retrieval and normalization
        prepared = self.prepare_import_data(params)

        if not prepared.get('success', True):
            return prepared

        data = prepared.get('data', [])
        if not data:
            return {"success": True, "rows_upserted": 0, "message": "No data to upsert"}

        config = prepared['config']
        obj_name = params.get('object') or params.get('table')

        if not obj_name:
            return {"success": False, "error": "Target object not specified"}
        # Strip schema prefix (e.g. "stripe.charges" → "charges") — parallels F-13.
        if isinstance(obj_name, str) and "." in obj_name:
            obj_name = obj_name.rsplit(".", 1)[-1]

        # Per-pipeline target namespace travels separately from the row data.
        # SaaS endpoints are fixed per resource so there is nothing to qualify;
        # we capture it (skipping the planner's "default" placeholder) for
        # observability rather than silently dropping it.
        namespace = str((params or {}).get('namespace') or (params or {}).get('db_or_schema') or "").strip()
        if namespace == "default":
            namespace = ""

        # Find resource endpoint + its id field. F13 — only resources that
        # declare a write verb (create/update/delete) are valid destinations; a
        # read-only resource (metabase 'search'/'task') is never a write target.
        resource_endpoints = {
            "customers": "/customers",
            "products": "/products",
        }
        resource_id_fields = {
            "customers": "id",
            "invoices": "id",
            "charges": "id",
            "payment_intents": "id",
            "subscriptions": "id",
            "products": "id",
            "prices": "id",
            "refunds": "id",
        }

        endpoint = resource_endpoints.get(obj_name)
        if not endpoint:
            return {"success": False, "error": f"Resource {obj_name!r} is not writable (no create/update/delete capability)"}
        # Idempotent upsert: match on key_fields (default the resource id field).
        # A record with an id PUTs to {endpoint}/{id} (idempotent by REST
        # semantics — re-running the same batch is a no-op delta); a record with
        # no id POSTs to create. Re-running therefore never duplicates rows.
        keys = (params or {}).get('key_fields') or (params or {}).get('keys')
        if isinstance(keys, str):
            keys = [keys]
        id_field = (keys[0] if keys else None) or resource_id_fields.get(obj_name, 'id')
        # Per-resource update verb: HubSpot/Intercom item routes accept PATCH
        # only and 405 on PUT. Defaults to PUT for resources that don't override.
        resource_update_methods = {
            "customers": "PUT",
            "invoices": "PUT",
            "charges": "PUT",
            "payment_intents": "PUT",
            "subscriptions": "PUT",
            "products": "PUT",
            "prices": "PUT",
            "refunds": "PUT",
        }
        update_method = resource_update_methods.get(obj_name, 'PUT')
        try:
            upserted = 0
            errors = []
            for record in data:
                rec_id = record.get(id_field) if isinstance(record, dict) else None
                if rec_id is not None and str(rec_id) != "":
                    result = self._make_request(update_method, f"{endpoint}/{rec_id}", config, data=record)
                    if not result.get('success') and result.get('status_code') == 404:
                        # target doesn't exist yet -> create
                        result = self._make_request('POST', endpoint, config, data=record)
                else:
                    result = self._make_request('POST', endpoint, config, data=record)
                if result.get('success'):
                    upserted += 1
                else:
                    errors.append(result.get('error', 'Unknown error'))
            return {
                "success": len(errors) == 0,
                "rows_upserted": upserted,
                "errors": errors[:10] if errors else [],
            }
        except Exception as e:
            return {"success": False, "error": str(e)}
    
