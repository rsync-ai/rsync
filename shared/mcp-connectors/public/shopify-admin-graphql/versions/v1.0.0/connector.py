def _flatten_value(v: Any) -> Any:
    """Serialize nested dicts/lists as JSON strings so Postgres can store them."""
    if isinstance(v, (dict, list)):
        return json.dumps(v, ensure_ascii=False, default=str)
    return v


def _flatten_row(row: Dict[str, Any]) -> Dict[str, Any]:
    """Convert all values in a record to Postgres-compatible scalars.

    psycopg2 raises ``can't adapt type 'dict'`` when a column value is a
    Python dict (e.g. nested GraphQL objects like ``plan: {displayName: ...}``).
    We JSON-serialize those values so they land as TEXT/JSONB.
    """
    return {k: _flatten_value(v) for k, v in row.items()}


def _extract_connection_rows(obj: Any, depth: int = 0) -> Optional[List[Dict[str, Any]]]:
    """Depth-first search for Relay connection rows inside a GraphQL object.

    Handles two standard Relay pagination patterns:
      - ``edges[].node``  — full Relay spec (Shopify, GitHub GraphQL v4, Linear, …)
      - ``nodes[]``       — shorthand available on many Relay-compliant APIs

    Recurses into dict-valued children ONLY (not into list-valued sub-fields
    such as ``tags``, ``features``, etc.) so incidental array attributes on a
    single-object response don't get mistaken for the primary result set.

    Returns ``None`` when no connection pattern is found, so callers can
    distinguish "nothing found" from "found an empty list".
    """
    if not isinstance(obj, dict) or depth > 4:
        return None
    # Relay edges pattern: {edges: [{node: {...}}, ...]}
    edges = obj.get("edges")
    if isinstance(edges, list):
        rows = [
            e["node"] for e in edges
            if isinstance(e, dict) and isinstance(e.get("node"), dict)
        ]
        return rows  # may be empty list — that's a valid "found but empty" signal
    # Relay nodes shortcut: {nodes: [{...}, ...]}  (GitHub, some Linear APIs)
    nodes = obj.get("nodes")
    if isinstance(nodes, list):
        rows = [n for n in nodes if isinstance(n, dict)]
        return rows
    # Recurse into dict-valued children to handle wrapped connections like
    # {"viewer": {"repositories": {"edges": [...]}}}  (GitHub viewer pattern)
    for v in obj.values():
        if isinstance(v, dict):
            result = _extract_connection_rows(v, depth + 1)
            if result is not None:
                return result
    return None


def _normalize_to_rows(data: Any) -> List[Dict[str, Any]]:
    """Best-effort flattening of a GraphQL response into a row list.

    Handles all common GraphQL response shapes at any nesting depth:
      1. Relay connection (edges/node) — direct or wrapped in a parent object:
           ``{"products": {"edges": [{"node": {...}}]}}``
           ``{"viewer": {"repositories": {"edges": [{"node": {...}}]}}}``
      2. Relay nodes shortcut:
           ``{"issues": {"nodes": [{...}, ...]}}``
      3. Top-level plain list (non-Relay):
           ``{"orders": [{...}, {...}]}``
      4. Single object:
           ``{"shop": {...}}``
    Falls back to wrapping ``data`` itself in a single-element list.

    All nested dicts/lists are JSON-serialised via ``_flatten_row`` so the
    downstream PostgreSQL connector (psycopg2) can store them without raising
    ``can't adapt type 'dict'``.
    """
    if isinstance(data, dict):
        if len(data) == 1:
            (only_value,) = data.values()
            if isinstance(only_value, dict):
                # Try Relay connection (edges/nodes) recursively — handles
                # both top-level and wrapped (e.g. viewer → repositories)
                rows = _extract_connection_rows(only_value)
                if rows is not None:
                    return [_flatten_row(r) for r in rows]
                # Fall back: plain list field (non-Relay) or single object
                for v in only_value.values():
                    if isinstance(v, list):
                        list_rows = [r for r in v if isinstance(r, dict)]
                        if list_rows:
                            return [_flatten_row(r) for r in list_rows]
                return [_flatten_row(only_value)]
            if isinstance(only_value, list):
                return [_flatten_row(r) for r in only_value if isinstance(r, dict)]
        # Multi-key dict: try connection extraction before treating as a single row
        rows = _extract_connection_rows(data)
        if rows is not None:
            return [_flatten_row(r) for r in rows]
        return [_flatten_row(data)]
    if isinstance(data, list):
        return [_flatten_row(r) for r in data if isinstance(r, dict)]
    return []


