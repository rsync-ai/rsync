    # ----- Generic export / import (alias to dispatcher) -------------------

    def export(
        self,
        params: Optional[Dict[str, Any]] = None,
    ) -> Dict[str, Any]:
        """Source-side export — base-class calling convention: export(params: Dict).

        _handle_tool_call always calls handler(normalized_args) where
        normalized_args is a dict.  The dict may contain:
            table / operation_name / operation — the GraphQL operation to run
            config  — connection config
            variables / filters — optional query variables
        """
        if isinstance(params, str):
            # Legacy positional call: export("products")
            operation_name = params
            cfg: Dict[str, Any] = {}
            variables: Dict[str, Any] = {}
        else:
            cfg = self._get_config(params)
            operation_name = (
                (params or {}).get("table")
                or (params or {}).get("endpoint")  # normalisation target for api_saas
                or (params or {}).get("operation_name")
                or (params or {}).get("operation")
            )
            variables = (params or {}).get("variables") or (params or {}).get("filters") or {}

        # Canonicalise schema-qualified table names BEFORE we route on
        # the operation. The HITL table picker persists names verbatim
        # from discover_schema, which joins schema+name for display
        # ("shopify.products"). The actual operation key is the suffix.
        # Strip here so downstream checks (e.g. the singleton-shop
        # detection below, dispatcher lookup) all see the canonical key.
        if isinstance(operation_name, str) and "." in operation_name:
            operation_name = operation_name.rsplit(".", 1)[-1]

        # Shopify Admin GraphQL Relay connections require "first" or "last" on
        # every connection field, AND enforce a hard cap of 250 per page.
        # The orchestrator's executor passes a `limit` derived from cost
        # estimation that can be in the tens of thousands; capping here keeps
        # Shopify happy and pagination handles the rest of the rows.
        if operation_name and operation_name not in ("shop",):
            variables = dict(variables or {})
            if "first" not in variables and "last" not in variables:
                requested = int((params or {}).get("limit") or 250)
                variables["first"] = max(1, min(requested, 250))

        if not operation_name:
            return {"success": False, "error": "Missing table/operation_name parameter"}

        # ---------------------------------------------------------------
        # Incremental sync — read `since` from params, translate to a
        # Shopify search-string predicate, and track max(updatedAt) so we
        # can return it as the watermark for the executor to persist.
        #
        # Contract (see shared/mcp-connectors/INCREMENTAL.md):
        #   params.since                  -> ISO-8601 timestamp (optional)
        #   variables.query                -> existing user filter (optional)
        #
        # The executor (executor.go:1370-1374) sets `since`, `updated_since`,
        # `modified_since`, and `modified_after` to the same value from the
        # checkpoint; we read whichever is present. NEVER log the raw value
        # below INFO — it's a customer-data leakage hint even though it's
        # just a date.
        # ---------------------------------------------------------------
        raw_since: Any = None
        if isinstance(params, dict):
            for key in ("since", "updated_since", "modified_since", "modified_after"):
                v = params.get(key)
                if v:
                    raw_since = v
                    break
        normalized_since = _normalize_iso_timestamp(raw_since)
        if raw_since and not normalized_since:
            # Don't crash on a malformed checkpoint; just degrade to full fetch.
            logger.warning(
                "[Incremental] %s: malformed since value, falling back to full fetch",
                operation_name,
            )

        incremental_capable = _INCREMENTAL_CAPABLE.get(operation_name, False)
        if incremental_capable and normalized_since:
            variables = dict(variables or {})
            existing_query = variables.get("query") if isinstance(variables.get("query"), str) else None
            combined = _compose_query_filter(existing_query, normalized_since)
            if combined:
                variables["query"] = combined
                logger.info(
                    "[Incremental] %s: applying updated_at filter (since=%s)",
                    operation_name, normalized_since,
                )

        # ---------------------------------------------------------------
        # SHOPIFY-BulkOps dispatch (opt-in via threshold or explicit flag)
        # ---------------------------------------------------------------
        # Bulk Operations is Shopify's high-throughput export path: submit
        # one query, Shopify processes it server-side, returns a downloadable
        # JSONL file. ~10x faster than paginated GraphQL for large stores
        # (>10k rows). For small stores (dev/Basic with <10k rows), the
        # bulk path's submit+poll overhead is net slower, so the regular
        # path is kept for them.
        #
        # Dispatch rules:
        #   use_bulk_ops=True        -> bulk path
        #   use_bulk_ops=False       -> regular path (today's behavior)
        #   use_bulk_ops="auto" (default):
        #     - count probe via <resource>Count
        #     - if count >= bulk_ops_threshold -> bulk path
        #     - else (or count unknown) -> regular path
        #
        # ANY bulk-path failure (userError, FAILED, timeout, download
        # error) falls back to the regular paginated path. Bulk ops
        # failure must NEVER cause export to fail.
        use_bulk_ops_raw = (params or {}).get("use_bulk_ops", "auto") if isinstance(params, dict) else "auto"
        bulk_threshold_raw = (params or {}).get("bulk_ops_threshold") if isinstance(params, dict) else None

        try:
            bulk_decision = self._decide_bulk_path(
                operation_name=operation_name,
                use_bulk_ops=use_bulk_ops_raw,
                bulk_threshold=bulk_threshold_raw,
                config=cfg,
            )
        except Exception as exc:  # pragma: no cover - defensive
            logger.warning("[BulkOps] dispatch decision raised, using regular path: %s", exc)
            bulk_decision = False

        if bulk_decision and _bulk_ops is not None:
            bulk_params = params if isinstance(params, dict) else {}
            bulk_result = self._try_bulk_export(operation_name=operation_name, config=cfg, params=bulk_params)
            if bulk_result is not None:
                return bulk_result
            # bulk_result is None == fall back to regular path; warning
            # already logged inside _try_bulk_export.

        # ---------------------------------------------------------------
        # Regular paginated path. Loops EVERY page of the Relay connection
        # inside this single export() call (Shopify caps a page at 250 rows),
        # accumulating all rows so tables in the 251–9,999 range — below the
        # bulk-ops threshold but above one page — return in full instead of
        # being silently truncated to the first 250. The watermark contract
        # below then scans the full set for max(updatedAt).
        #
        # Singleton operations (e.g. ``shop``) have no connection / ``first``
        # argument and take the single-call path unchanged.
        #
        # Resume: when a hard cap (record/page) stops the loop early it
        # returns ``has_more=True`` + ``next_cursor``; the executor replays
        # that as ``params.cursor`` on the next call. The cap is only reached
        # when bulk-ops is force-disabled on a very large table — auto-mode
        # routes ≥10k-row tables to the bulk path before reaching here.
        # ---------------------------------------------------------------
        page_size = variables.get("first") if isinstance(variables, dict) else None
        next_cursor: Optional[str] = None
        has_more = False
        if page_size:
            start_after = (params or {}).get("cursor") if isinstance(params, dict) else None
            max_records = int((params or {}).get("limit") or 10000) if isinstance(params, dict) else 10000

            def _execute_page(page_vars: Dict[str, Any]) -> Any:
                return self.execute_operation(
                    operation_name, variables=page_vars or None, config=cfg or None
                )

            try:
                rows, next_cursor, has_more = GraphQLPaginationHandler().fetch_all_pages(
                    _execute_page,
                    variables,
                    page_size=int(page_size),
                    max_records=max_records,
                    start_after=start_after,
                    row_extractor=_normalize_to_rows,
                )
            except Exception as exc:
                return {"success": False, "error": str(exc)}
        else:
            # Singleton / non-connection operation (e.g. ``shop``): single call.
            try:
                data = self.execute_operation(operation_name, variables=variables or None, config=cfg or None)
            except Exception as exc:
                return {"success": False, "error": str(exc)}
            rows = _normalize_to_rows(data)

        cols = list(rows[0].keys()) if rows else []

        response: Dict[str, Any] = {
            "success": True,
            "data": rows,
            "columns": cols,
            "row_count": len(rows),
            "has_more": has_more,
        }
        if has_more and next_cursor:
            response["next_cursor"] = next_cursor
            response["paging_mode"] = "cursor"

        # Compute and attach the watermark when the resource is incremental-
        # capable. The executor reads ``stats.watermark = {field, value}``
        # (executor.go:1436-1440) and persists it; on the next run it sends
        # the value back as ``since``.
        #
        # Edge cases (per contract):
        #   * No rows seen AND a prior `since` exists  -> echo `since` so the
        #     existing checkpoint stays advanced rather than being cleared.
        #   * No rows seen AND no prior `since`       -> omit watermark (the
        #     executor keeps whatever it had, which is nothing — first run).
        #   * Resource not incremental-capable         -> never attach
        #     watermark; executor preserves prior checkpoint.
        if incremental_capable:
            running = _max_updated_at(rows, None)
            watermark_value: Optional[str] = None
            if running is not None:
                watermark_value = running[0]
            elif normalized_since:
                # 0 rows returned but we had a prior watermark — keep it.
                watermark_value = normalized_since

            if watermark_value:
                response["stats"] = {
                    "watermark": {
                        "field": "last_modified",
                        "value": watermark_value,
                    }
                }
                response["max_watermark"] = watermark_value

        return response

    # ----- Bulk Operations helpers (SHOPIFY-BulkOps) ----------------------

    # Shopify resources that expose a free <X>Count query in Admin 2024-10.
    # Resources outside this set don't get auto-bulk (we don't gamble on
    # bulk's submit+poll overhead for unknown sizes — better to keep the
    # regular path's predictable per-page latency).
    _BULK_COUNT_CAPABLE = {"products", "orders", "customers", "collections"}

    def _decide_bulk_path(
        self,
        *,
        operation_name: str,
        use_bulk_ops: Any,
        bulk_threshold: Any,
        config: Dict[str, Any],
    ) -> bool:
        """Return True iff this export should attempt the bulk path."""
        if _bulk_ops is None:
            return False

        # Explicit override wins. Accept the same values the orchestrator
        # might serialize: bool, "true"/"false", "True"/"False", "auto".
        if isinstance(use_bulk_ops, bool):
            return use_bulk_ops
        if isinstance(use_bulk_ops, str):
            v = use_bulk_ops.strip().lower()
            if v in ("true", "yes", "1", "force"):
                return True
            if v in ("false", "no", "0", "off"):
                return False
            # "auto" / "" / anything else -> threshold-based decision.

        # "auto" mode: count probe + threshold.
        if operation_name == "shop":
            # shop is a singleton, never benefits from bulk ops.
            return False
        if operation_name not in self._BULK_COUNT_CAPABLE:
            # No reliable count query for this resource (e.g. inventory_items).
            # Don't gamble on bulk; stay on regular pagination.
            return False

        # Resolve threshold: param > env > default(10_000).
        try:
            threshold = int(bulk_threshold) if bulk_threshold is not None else _bulk_ops.env_threshold(10000)
        except (TypeError, ValueError):
            threshold = _bulk_ops.env_threshold(10000)

        if threshold <= 0:
            # threshold=0 means "force bulk in auto mode".
            return True

        count = self._best_effort_count(operation_name, config)
        if count is None or count < 0:
            return False
        return count >= threshold

    def _try_bulk_export(
        self,
        *,
        operation_name: str,
        config: Dict[str, Any],
        params: Dict[str, Any],
    ) -> Optional[Dict[str, Any]]:
        """Run the bulk-export path. Return None on failure (caller falls back).

        Returns the export() success-shape dict on completion (even with
        zero rows). Returns None when bulk ops failed and the caller
        should fall back to regular pagination.
        """
        if _bulk_ops is None:
            return None

        op = GRAPHQL_OPERATIONS.get(operation_name)
        if op is None:
            logger.warning("[BulkOps] no GraphQL op for %r, falling back", operation_name)
            return None
        inner_query = op.get("query") or ""
        if not inner_query.strip():
            return None

        cfg_copy = dict(config or {})

        # Adapter: post_graphql callable bound to this connector's auth +
        # endpoint. Returns the GraphQL `data` payload, raises GraphQLError
        # on transport/HTTP/GraphQL-error envelope failure.
        def _post_graphql(query: str, variables: Optional[Dict[str, Any]]) -> Dict[str, Any]:
            return self._execute_graphql(query, variables, cfg_copy, timeout=60)

        # Adapter: get_url for the JSONL download. The bulk-op URL is a
        # Google Cloud Storage signed URL — auth headers MUST NOT be sent
        # (some signed URLs reject extra Authorization). Use a fresh
        # requests.get with no headers added.
        def _get_url(url: str, timeout: int) -> tuple[int, str]:
            # SSRF guard: the bulk-op download URL comes from Shopify's
            # response (a GCS signed URL). Guard it defensively so a
            # malicious/MITM'd response can't redirect the fetch to an
            # internal target. GCS URLs are public, so legit traffic passes.
            try:
                from base_connector import _ssrf_check_url
                _ssrf_reason = _ssrf_check_url(url)
            except Exception:
                _ssrf_reason = None
            if _ssrf_reason is not None:
                raise GraphQLError(f"SSRF guard blocked bulk download: {_ssrf_reason}")
            resp = requests.get(url, timeout=timeout)
            return resp.status_code, resp.text

        timeout_sec = _bulk_ops.env_timeout()
        poll_interval = _bulk_ops.env_poll_interval()

        try:
            result = _bulk_ops.run_bulk_export(
                inner_query=inner_query,
                post_graphql=_post_graphql,
                get_url=_get_url,
                poll_interval_sec=poll_interval,
                timeout_sec=timeout_sec,
            )
        except Exception as e:
            # Belt-and-suspenders: run_bulk_export shouldn't raise, but
            # if it does, never let bulk-ops failure break export().
            logger.warning("[BulkOps] run_bulk_export raised, falling back: %s", e)
            return None

        if not result.ok:
            logger.warning(
                "[BulkOps] %s failed (status=%s, elapsed=%.1fs, error=%s), falling back to regular pagination",
                operation_name,
                result.status,
                result.elapsed_sec,
                result.error,
            )
            return None

        # Success — normalize rows the same way the regular path does so
        # the downstream sink sees identical row shape regardless of which
        # path produced the data.
        rows = [_flatten_row(r) for r in (result.rows or []) if isinstance(r, dict)]
        cols = list(rows[0].keys()) if rows else []
        logger.info(
            "[BulkOps] %s completed via bulk path: rows=%d, object_count=%s, elapsed=%.1fs",
            operation_name,
            len(rows),
            result.object_count,
            result.elapsed_sec,
        )
        bulk_response: Dict[str, Any] = {
            "success": True,
            "data": rows,
            "columns": cols,
            "row_count": len(rows),
            "has_more": False,
            "bulk_ops": {
                "used": True,
                "operation_id": result.operation_id,
                "object_count": result.object_count,
                "elapsed_sec": result.elapsed_sec,
            },
        }

        # Emit the incremental watermark exactly as the regular path does, so a
        # ≥10k-row table routed through bulk ops still advances its checkpoint
        # (otherwise every incremental run would re-export the whole table).
        # Bulk JSONL returns the full result set, so max(updatedAt) over `rows`
        # is the true high-water mark. Mirrors the regular-path contract:
        # 0 rows + prior `since` -> echo `since`; not incremental-capable -> skip.
        if _INCREMENTAL_CAPABLE.get(operation_name, False):
            since_value = None
            for key in ("since", "updated_since", "modified_since", "modified_after"):
                v = (params or {}).get(key)
                if v:
                    since_value = _normalize_iso_timestamp(v)
                    break
            running = _max_updated_at(rows, None)
            watermark_value = running[0] if running is not None else since_value
            if watermark_value:
                bulk_response["stats"] = {
                    "watermark": {"field": "last_modified", "value": watermark_value}
                }
                bulk_response["max_watermark"] = watermark_value

        return bulk_response

    # ----- Destination (write) ---------------------------------------------

    @staticmethod
    def _resolve_dest_resource(params: Optional[Dict[str, Any]]) -> str:
        """Resolve the writable resource name from the call params.

        The sink sends the destination as ``table`` (or ``object``); a HITL
        round-trip may prefix it with the connector's schema ("shopify.products")
        — strip that. A singular alias ("product") maps to "products".
        """
        raw = (
            (params or {}).get("table")
            or (params or {}).get("endpoint")  # normalisation target for api_saas
            or (params or {}).get("object")
            or ""
        )
        name = str(raw).strip()
        if "." in name:
            name = name.rsplit(".", 1)[-1]
        if name not in _WRITABLE_RESOURCES and (name + "s") in _WRITABLE_RESOURCES:
            name = name + "s"
        return name

    def _write_records(
        self,
        resource: str,
        rows: List[Dict[str, Any]],
        cfg: Dict[str, Any],
        *,
        mode: str,
    ) -> Tuple[int, List[str]]:
        """Run the per-record create/update mutations for a writable resource.

        ``mode`` is "append" (always create) or "upsert" (update when the record
        carries a product GID, else create). Returns ``(written, errors)``;
        ``written`` counts only rows whose mutation returned NO ``userErrors``
        (Shopify reports validation failures there on a 200, not via the
        top-level GraphQL errors envelope).
        """
        spec = _WRITABLE_RESOURCES[resource]
        build_input = spec["build_input"]
        written = 0
        errors: List[str] = []
        for idx, row in enumerate(rows or []):
            try:
                input_obj, is_update = build_input(row)
                if mode == "append":
                    # Append never updates: drop any id so it always creates.
                    is_update = False
                    input_obj.pop("id", None)
                if is_update:
                    mutation = spec["update_mutation"]
                    result_key = spec["update_result_key"]
                else:
                    mutation = spec["create_mutation"]
                    result_key = spec["create_result_key"]
                data = self._execute_graphql(mutation, {"input": input_obj}, cfg)
            except GraphQLError as e:
                errors.append(f"record {idx}: {e}")
                continue
            payload = (data or {}).get(result_key) or {}
            user_errors = payload.get("userErrors") or []
            if user_errors:
                msg = "; ".join(
                    f"{'.'.join(ue.get('field') or []) or '?'}: {ue.get('message')}"
                    for ue in user_errors[:3] if isinstance(ue, dict)
                )
                errors.append(f"record {idx}: {msg}")
            else:
                written += 1
        return written, errors

    def _destination_write(
        self,
        params: Optional[Dict[str, Any]],
        *,
        mode: str,
    ) -> Dict[str, Any]:
        """Shared body for import_data (append) / upsert_data (upsert).

        Reads rows from the sink's ``data`` key via ``prepare_import_data``
        (which also resolves claim-checked / staged batches), falling back to
        raw ``data``/``records`` if the base helper is unavailable. Returns the
        SaaS-destination shape ``{success, rows_inserted|rows_upserted, errors}``.
        """
        count_key = "rows_upserted" if mode == "upsert" else "rows_inserted"

        # Legacy positional / string call — nothing to write.
        if params is None or isinstance(params, str):
            return {"success": True, count_key: 0, "message": "No data to write"}

        cfg = self._get_config(params)
        resource = self._resolve_dest_resource(params)
        if resource not in _WRITABLE_RESOURCES:
            return {
                "success": False,
                count_key: 0,
                "error": (
                    f"Shopify destination supports {sorted(_WRITABLE_RESOURCES)}; "
                    f"got '{resource or '(none)'}'"
                ),
            }

        rows: Optional[List[Dict[str, Any]]] = None
        try:
            prepared = self.prepare_import_data(params)
            if isinstance(prepared, dict):
                if not prepared.get("success", True):
                    return prepared
                rows = prepared.get("data")
                if prepared.get("config"):
                    cfg = prepared["config"]
        except Exception:  # pragma: no cover - defensive
            rows = None
        if rows is None:
            rows = (params.get("data") or params.get("records") or [])

        if not rows:
            return {"success": True, count_key: 0, "message": "No data to write"}

        written, errors = self._write_records(resource, rows, cfg, mode=mode)
        return {
            "success": len(errors) == 0,
            count_key: written,
            "errors": errors[:10],
        }

    def import_data(
        self,
        params: Optional[Dict[str, Any]] = None,
    ) -> Dict[str, Any]:
        """Destination APPEND: create one Shopify record per row.

        The sink calls ``shopify-admin-graphql_import_data`` for keyless /
        append-mode destinations, sending rows under ``data`` and the resource
        under ``table``. Returns ``{success, rows_inserted, errors}``.
        """
