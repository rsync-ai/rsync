class ShopifyConnector(BaseMCPConnector):
    """Shopify GraphQL connector."""

    DEFAULT_ENDPOINT = "https://{shop}.myshopify.com/admin/api/2024-10/graphql.json"

    def __init__(self) -> None:
        super().__init__()
        self.connector_type = "shopify-admin-graphql"
        self.display_name = "Shopify"
        # Must match metadata.json "category". Left undeclared, BaseMCPConnector
        # defaults to "relational_db" (base_connector.py:1000), so Go read api_saas
        # from metadata.json while Python normalised params as a relational DB.
        self.connector_category = "api_saas"

    @staticmethod
    def _get_config(params: Optional[Dict[str, Any]]) -> Dict[str, Any]:
        """Unwrap config from MCP tool-call wrapper.

        _handle_tool_call passes the full arguments dict, which wraps the
        actual connection config under a ``"config"`` key. Accept both shapes:
          - {"config": {"shop": ..., "access_token": ...}}  ← tools/call path
          - {"shop": ..., "access_token": ...}              ← direct stdio path
        """
        if not params:
            return {}
        if "config" in params and isinstance(params["config"], dict):
            return dict(params["config"])
        return dict(params)

    # ----- HTTP transport ---------------------------------------------------

    def _resolve_endpoint(self, config: Dict[str, Any]) -> str:
        """Resolve the GraphQL endpoint URL.

        The spec's base_url carries a runtime `{shop}` placeholder that is
        substituted from `config` at call time. The shop is STRICTLY validated
        (single DNS label) and the resolved host is pinned to
        ``<label>.myshopify.com`` so the tenant's X-Shopify-Access-Token can
        never be POSTed to an attacker host — even via a raw `endpoint`
        override. See ``_sanitize_shop`` above.
        """
        try:
            shop = _sanitize_shop(config.get("shop"))
        except ValueError as e:
            # Fail closed using the connector's transport error type so callers
            # (test_connection / export) surface it cleanly instead of raising
            # an uncaught ValueError.
            raise GraphQLError(f"invalid shop: {e}") from e

        endpoint = config.get("endpoint") or self.DEFAULT_ENDPOINT
        # Merge optional-placeholder defaults so a single missing key doesn't
        # suppress all substitutions (e.g. {version} defaults to 2024-10).
        # Force the validated shop label into the substitution set so a caller
        # cannot smuggle a host-escaping value through config["shop"].
        defaults = {
            "version": "2024-10",
        }
        sub = {**defaults, **config, "shop": shop}
        try:
            resolved = endpoint.format(**sub)
        except (KeyError, IndexError):
            resolved = endpoint

        # Defense in depth: whatever the template or `endpoint` override
        # produced, the host MUST be <shop>.myshopify.com. Blocks an override
        # that points the access-token POST at a foreign host.
        parts = urlsplit(resolved)
        expected_host = f"{shop}{_SHOPIFY_HOST_SUFFIX}".lower()
        if parts.scheme not in ("http", "https") or (parts.hostname or "").lower() != expected_host:
            raise GraphQLError(
                f"refusing to send Shopify credentials to non-myshopify host "
                f"{parts.hostname!r} (resolved endpoint {resolved!r})"
            )
        return resolved

    # ----- Auth dispatcher (Phase 12: multi-auth) ---------------------------
    # Each supported method's wire config is baked in at generation time.
    # The user picks `config["auth_method"]` at connection time and the
    # dispatcher formats the request accordingly. Falls back to the spec's
    # default `auth.type` when the user doesn't specify.

    SUPPORTED_AUTH_METHODS: List[Dict[str, Any]] = [
        {
            "method": "custom_header",
            "header_name": "X-Shopify-Access-Token",
            "header_prefix": "",
            "config_keys": ["access_token", "token"],
            "description": "Shopify Admin API access token (private app or custom app token)",
        },
        {
            "method": "oauth2",
            "header_name": "X-Shopify-Access-Token",
            "header_prefix": "",
            "config_keys": ["access_token"],
            "description": "OAuth 2.0 \u2014 for public/custom Shopify Apps installed on a shop",
        },
    ]

    DEFAULT_AUTH_METHOD = "custom_header"

    def _resolve_auth_method(self, config: Dict[str, Any]) -> Optional[Dict[str, Any]]:
        """Pick the auth method to use for a request.

        Priority:
          1. `config['auth_method']` if it matches a supported method
          2. The connector's DEFAULT_AUTH_METHOD
          3. The first supported method declared
        """
        requested = (config.get("auth_method") or "").strip().lower()
        for m in self.SUPPORTED_AUTH_METHODS:
            if m["method"] == requested:
                return m
        for m in self.SUPPORTED_AUTH_METHODS:
            if m["method"] == self.DEFAULT_AUTH_METHOD:
                return m
        return self.SUPPORTED_AUTH_METHODS[0] if self.SUPPORTED_AUTH_METHODS else None

    def _build_auth_headers(self, config: Dict[str, Any]) -> Dict[str, str]:
        """Format auth headers based on the user's chosen method.

        For basic auth, returns empty headers (the connector uses
        `requests.auth=(user, pass)` instead).
        """
        method = self._resolve_auth_method(config)
        if method is None:
            return {}

        wire = method["method"]
        if wire == "none":
            return {}
        if wire == "basic":
            return {}  # handled via auth=(user, pass) in _execute_graphql

        # Bearer / api_key / custom_header / oauth2 — all just put a token in
        # a header. Differences are header_name + header_prefix.
        token = self._resolve_credential(config, *method["config_keys"])
        if not token:
            return {}

        header_name = method["header_name"] or "Authorization"
        prefix = method["header_prefix"] or ""
        if prefix and not prefix.endswith(" "):
            prefix = prefix + " "
        return {header_name: f"{prefix}{token}".strip()}

    @staticmethod
    def _resolve_credential(config: Dict[str, Any], *keys: str) -> Optional[str]:
        """Look up a credential value from config or environment.

        Tries each key in `keys` against `config`, then falls back to the
        env var derived from the key name (e.g. `access_token` → `ACCESS_TOKEN`).
        """
        for k in keys:
            v = config.get(k)
            if v:
                return str(v)
        for k in keys:
            v = os.environ.get(k.upper())
            if v:
                return v
        return None

    # ----- GraphQL execution ----------------------------------------------

    def _execute_graphql(
        self,
        query: str,
        variables: Optional[Dict[str, Any]],
        config: Dict[str, Any],
        *,
        timeout: int = 30,
    ) -> Dict[str, Any]:
        """POST a GraphQL document and return the `data` payload.

        - Sends Content-Type: application/json (required by GraphQL spec).
        - Surfaces any `errors[]` envelope as a GraphQLError.
        - Raises on non-200 responses.
        """
        endpoint = self._resolve_endpoint(config)
        headers = {"Content-Type": "application/json", "Accept": "application/json"}
        headers.update(self._build_auth_headers(config))

        body = {"query": query}
        if variables is not None:
            body["variables"] = variables

        # Basic auth uses requests.auth=(user, pass) instead of headers.
        # The dispatcher returns empty headers in that case; we recompute here.
        method = self._resolve_auth_method(config)
        auth = None
        if method and method["method"] == "basic":
            auth = (
                self._resolve_credential(config, "username") or "",
                self._resolve_credential(config, "password") or "",
            )

        # SSRF guard: the endpoint is resolved from connection config
        # (`endpoint` override or `{shop}` substitution), so refuse to send
        # the X-Shopify-Access-Token to internal services / private IPs /
        # loopback / link-local before the POST. Mirrors the generated
        # GraphQL template (connector_graphql.py.j2). Best-effort import so
        # an older base_connector copy without the helper degrades to no-op.
        # Opt-out for dev: MCP_ALLOW_PRIVATE_NETWORKS=true.
        try:
            from base_connector import _ssrf_check_url
            _ssrf_reason = _ssrf_check_url(endpoint)
        except Exception:
            _ssrf_reason = None
        if _ssrf_reason is not None:
            raise GraphQLError(f"SSRF guard blocked outbound GraphQL call: {_ssrf_reason}")

        try:
            resp = requests.post(endpoint, headers=headers, json=body, timeout=timeout, auth=auth)
        except requests.RequestException as e:
            raise GraphQLError(f"transport error: {e}") from e

        if resp.status_code != 200:
            raise GraphQLError(
                f"HTTP {resp.status_code}: {resp.text[:200]}",
                status_code=resp.status_code,
            )

        try:
            payload = resp.json()
        except ValueError as e:
            raise GraphQLError(f"invalid json response: {e}") from e

        # GraphQL `errors[]` envelope — non-empty means failure even on 200 OK
        if isinstance(payload, dict) and payload.get("errors"):
            errs = payload.get("errors") or []
            msg = "; ".join(str(e.get("message") or "") for e in errs[:3] if isinstance(e, dict))
            raise GraphQLError(f"graphql errors: {msg}", errors=errs)

        return (payload or {}).get("data") or {}

    # ----- Generic dispatcher (lazy-mode core) ------------------------------

    def execute_operation(
        self,
        operation_name: str,
        variables: Optional[Dict[str, Any]] = None,
        config: Optional[Dict[str, Any]] = None,
    ) -> Dict[str, Any]:
        """Execute a registered operation by name. Lazy-mode dispatch.

        Tolerates schema-qualified operation names. ``discover_schema``
        emits tables with a ``schema`` field set to "shopify"; the UI
        joins schema+name for display ("shopify.products") and the HITL
        table-picker persists that joined string verbatim into
        ``pipelines.config.selected_tables``. Downstream when the
        executor calls this method with the persisted name, "shopify."
        is just a leading namespace — the actual operation key is
        the suffix ("products"). Strip the leading "<schema>." (where
        schema matches the connector_type's vendor prefix) so a HITL
        round-trip doesn't break SaaS pipelines.

        This is also called by all the per-operation methods below.
        """
        cfg = self._get_config(config)
        op_key = (operation_name or "").strip()
        op = GRAPHQL_OPERATIONS.get(op_key)
        if op is None and "." in op_key:
            # Try the suffix after the LAST dot — covers both "shopify.products"
            # and any future per-namespace shape like "shopify.admin.products".
            suffix = op_key.rsplit(".", 1)[-1]
            op = GRAPHQL_OPERATIONS.get(suffix)
        if op is None:
            raise GraphQLError(f"unknown operation '{operation_name}'")
        return self._execute_graphql(op["query"], variables or {}, cfg)

    # ----- Required core operations ----------------------------------------

    def test_connection(self, config: Optional[Dict[str, Any]] = None) -> Dict[str, Any]:
        """Verify connectivity by issuing a minimal `__typename` query."""
        cfg = self._get_config(config)
        try:
            data = self._execute_graphql(
                query="{ __typename }",
                variables=None,
                config=cfg,
            )
            return {"success": True, "details": {"typename": data.get("__typename")}}
        except GraphQLError as e:
            return {"success": False, "error": str(e)}

    def validate_config(self, config: Optional[Dict[str, Any]] = None) -> Dict[str, Any]:
        """Confirm required config fields are present."""
        cfg = self._get_config(config)
        required: List[str] = [
"shop",
"access_token",
        ]
        missing = [
            name for name in required
            if not (cfg.get(name) or os.environ.get(name.upper()))
        ]
        if missing:
            return {"valid": False, "missing": missing}
        return {"valid": True}

    def discover_schema(self, config: Optional[Dict[str, Any]] = None) -> Dict[str, Any]:
        """Discover the source schema via real GraphQL introspection.

        Implements the canonical discovery contract every source connector
        must satisfy (see docs/discovery.md):

            {
              "success": bool,
              "tables": [
                {
                  "name":        str,          # resource / table name
                  "schema":      str | None,   # namespace (db/schema)
                  "columns":     [             # populated when available
                    {"name": str, "type": str}
                  ],
                  "row_count":   int,          # -1 sentinel == unknown
                  "description": str | None,
                  "type":        "query|table|collection",
                },
                ...
              ],
              "operations": [...],
              "error":      str | None,
            }

        The previous implementation hardcoded the table list with empty
        columns and no row counts, so the HITL table-selection UI showed
        "products / orders / customers …" with `columns=0, row_count=0`
        even when the connection was broken or pointed at an empty
        store. That hid auth errors and gave users no schema signal.
        We now:

          1. Verify auth via ``test_connection`` and fail closed on
             auth errors instead of returning a hardcoded list.
          2. Run a GraphQL ``__type`` introspection query for every
             known operation to enumerate the leaf fields of the
             response type (after unwrapping Relay ``*Connection``
             wrappers down to the underlying ``Node`` type).
          3. Best-effort row counts using Shopify's ``<resource>Count``
             queries — leave ``row_count = -1`` when the count query is
             not exposed by the API (the UI knows ``-1`` means unknown
             and renders nothing rather than a misleading zero).

        Per-table errors are localised: if introspection fails for one
        resource we keep going and just leave its columns empty, so a
        partial schema is still better than nothing.
        """
        cfg = self._get_config(config)

        # 1. Fail-closed auth check. The hardcoded fallback used to
        # silently succeed; we'd rather tell the user their token is
        # bad than show them a fake schema.
        try:
            auth_check = self.test_connection(cfg)
        except Exception as e:  # pragma: no cover - defensive
            return {
                "success": False,
                "error": f"connection test raised: {e}",
                "tables": [],
                "operations": [],
            }
        if not auth_check.get("success"):
            return {
                "success": False,
                "error": "auth check failed: " + str(auth_check.get("error", "unknown")),
                "tables": [],
                "operations": [],
            }

        # 2 & 3. For each operation, introspect its return type and
        # best-effort count. Each per-resource lookup is independent —
        # an introspection failure on `orders` shouldn't take down
        # `products`.
        tables: List[Dict[str, Any]] = []
        for name, op in GRAPHQL_OPERATIONS.items():
            return_type = op.get("return_type") or ""
            raw_fields = self._introspect_raw_fields(self._unwrap_connection_type(return_type), cfg)
            row_count = self._best_effort_count(op.get("graphql_name") or name, cfg)
            # Canonical column types — sinks rely on canonical, not raw GraphQL names.
            columns = [
                {"name": fname, "type": canonicalize_type(raw_type)}
                for fname, raw_type in raw_fields
            ]
            # PK detection: any field whose GraphQL type is `ID` is a PK
            # candidate. Generic across all Relay-compliant GraphQL APIs;
            # Shopify resources each expose exactly one `id: ID!`.
            pk_fields = [fname for fname, raw_type in raw_fields if raw_type == "ID"]
            tables.append({
                "name": name,
                "schema": "shopify",
                "columns": columns,
                "row_count": row_count,
                "description": op.get("description", ""),
                "type": op.get("operation_type", "query"),
                "primary_keys": pk_fields,
                "primary_key_source": "declared" if pk_fields else "synthetic",
            })

        ops = [
            {"name": name, **{k: v for k, v in op.items() if k != "query"}}
            for name, op in GRAPHQL_OPERATIONS.items()
        ]
        return {
            "success": True,
            "tables": tables,
            "operations": ops,
        }

    # ----- Introspection helpers -------------------------------------------
    #
    # These are local to the Shopify connector for now but match the
    # canonical discovery contract documented in
    # llm-service/src/agents/tool_generator/templates/connector_graphql.py.j2
    # — the GraphQL template emits the same helpers so newly-generated
    # connectors comply with the contract by default.

    @staticmethod
    def _unwrap_connection_type(type_name: str) -> str:
        """Strip Relay Connection wrappers so we introspect the node type.

        Shopify (and most Relay-compliant GraphQL APIs) wrap list results
        in ``<X>Connection`` { edges { node: X, cursor }, pageInfo }.
        The interesting fields live on ``X``, not ``XConnection``. Without
        this unwrap, introspection of ``ProductConnection`` returns just
        ``edges`` and ``pageInfo`` which is useless to a table-selection
        UI.
        """
        if not type_name:
            return ""
        if type_name.endswith("Connection"):
            return type_name[:-len("Connection")]
        return type_name

    def _introspect_raw_fields(self, target_type: str, config: Dict[str, Any]) -> List[tuple]:
        """Return ``[(field_name, raw_gql_type_name)]`` for a GraphQL type.

        Keeps the raw GraphQL type name (e.g. ``ID``, ``String``,
        ``MoneyBag``) so callers can both (a) canonicalize for the
        generic pipeline and (b) detect ``ID`` fields for primary-key
        declaration. Returns ``[]`` when introspection is unavailable.
        """
        if not target_type:
            return []
        introspect = (
            "query IntrospectType($name: String!) {"
            "  __type(name: $name) {"
            "    name kind"
            "    fields { name type { name kind ofType { name kind ofType { name kind } } } }"
            "  }"
            "}"
        )
        try:
            data = self._execute_graphql(introspect, {"name": target_type}, config)
        except Exception:
            return []
        type_info = data.get("__type") if isinstance(data, dict) else None
        if not isinstance(type_info, dict):
            return []
        out: List[tuple] = []
        for f in type_info.get("fields") or []:
            if not isinstance(f, dict):
                continue
            fname = f.get("name", "")
            raw_type = self._flatten_graphql_type(f.get("type"))
            out.append((fname, raw_type))
        return out

    def _introspect_columns(self, target_type: str, config: Dict[str, Any]) -> List[Dict[str, Any]]:
        """Canonical-typed column list. Kept for callers that don't need PK info."""
        return [
            {"name": fname, "type": canonicalize_type(raw_type)}
            for fname, raw_type in self._introspect_raw_fields(target_type, config)
        ]

    def _flatten_graphql_type(self, type_node: Optional[Dict[str, Any]]) -> str:
        """Walk a GraphQL type-ref chain (NonNull / List wrappers) to the leaf name."""
        if not isinstance(type_node, dict):
            return "Unknown"
        name = type_node.get("name")
        if name:
            return name
        of_type = type_node.get("ofType")
        if of_type is not None:
            return self._flatten_graphql_type(of_type)
        return type_node.get("kind") or "Unknown"

    def _best_effort_count(self, graphql_resource: str, config: Dict[str, Any]) -> int:
        """Return the row count for a resource via Shopify's ``<X>Count`` queries.

        Shopify exposes zero-cost count queries for many top-level
        resources (``productsCount``, ``ordersCount``, ``customersCount``,
        ``collectionsCount``). Resources without a count query are not
        an error — we return ``-1`` to mean "unknown" so the UI can
        render "?" instead of a misleading zero.
        """
        # Only resources known to expose a count query in the Admin API
        # v2024-10. Cheaper than blindly probing every operation.
        count_capable = {"products", "orders", "customers", "collections"}
        if graphql_resource not in count_capable:
            return -1
        query = "query Count { %sCount { count } }" % graphql_resource
        try:
            data = self._execute_graphql(query, None, config)
        except Exception:
            return -1
        if not isinstance(data, dict):
            return -1
        block = data.get("%sCount" % graphql_resource)
        if isinstance(block, dict):
            v = block.get("count")
            if isinstance(v, int):
                return v
        if isinstance(block, int):
            return block
        return -1

