def _sanitize_shop(raw: Optional[str]) -> str:
    """Validate a user-supplied Shopify ``shop`` and return its bare store
    subdomain (a single DNS label).

    Accepts either a bare label ("acme") or the full domain
    ("acme.myshopify.com"). Rejects anything else — an embedded
    scheme/path/'@'/'#'/'/', a foreign host, an IP literal, or an empty value —
    by raising ValueError, so the access token can never be routed to an
    attacker host.
    """
    s = (raw or "").strip()
    if s.lower().endswith(_SHOPIFY_HOST_SUFFIX):
        s = s[: -len(_SHOPIFY_HOST_SUFFIX)]
    s = s.strip().strip(".")
    if not s:
        raise ValueError("shop is required (e.g. 'acme' for acme.myshopify.com)")
    if not _SHOP_LABEL_RE.match(s):
        raise ValueError(
            f"invalid Shopify shop {raw!r}: expected a store subdomain such as "
            f"'acme' or 'acme.myshopify.com' (a single DNS label)"
        )
    return s


