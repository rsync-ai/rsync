def _build_product_input(record: Dict[str, Any]) -> Tuple[Dict[str, Any], bool]:
    """Map an incoming record onto a Shopify ``ProductInput``.

    Returns ``(input_dict, is_update)``. ``is_update`` is True when the record
    carries a Shopify product GID (``gid://shopify/Product/...``) — those route
    to productUpdate; everything else is a productCreate. Applies field-name
    aliases (description→descriptionHtml, product_type→productType, …) and
    coerces ``tags`` (CSV string → list) and ``status`` (→ upper-case enum).
    """
    rec = dict(record or {})
    for src, dst in _PRODUCT_FIELD_ALIASES.items():
        if src in rec and dst not in rec and rec.get(src) is not None:
            rec[dst] = rec[src]

    pid = rec.get("id") or rec.get("admin_graphql_api_id")
    is_update = isinstance(pid, str) and pid.startswith(_PRODUCT_GID_PREFIX)

    out: Dict[str, Any] = {}
    if is_update:
        out["id"] = pid
    for k in _PRODUCT_INPUT_FIELDS:
        if k in rec and rec[k] is not None:
            out[k] = rec[k]

    tags = out.get("tags")
    if isinstance(tags, str):
        out["tags"] = [t.strip() for t in tags.split(",") if t.strip()]
    status = out.get("status")
    if isinstance(status, str):
        out["status"] = status.upper()
    return out, is_update


