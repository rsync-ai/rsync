_SHOPIFY_UPDATED_AT_FIELD = "updated_at"


def _normalize_iso_timestamp(raw: Any) -> Optional[str]:
    """Best-effort parse of an arbitrary ISO-8601 string into a Shopify-safe form.

    The executor sends ``since`` as whatever value the prior run wrote into
    ``pipeline_checkpoints.position.watermark.value``. We accept any
    standard ISO-8601 shape and re-emit ``YYYY-MM-DDTHH:MM:SSZ`` which
    Shopify's search parser handles unambiguously.

    Returns ``None`` for empty / non-string / unparseable input, so callers
    can fall back to a full fetch instead of crashing.
    """
    if raw is None:
        return None
    if not isinstance(raw, str):
        return None
    s = raw.strip()
    if not s:
        return None
    # Accept trailing Z by mapping to +00:00 for fromisoformat (Python 3.10).
    candidate = s.replace("Z", "+00:00") if s.endswith("Z") else s
    try:
        dt = datetime.fromisoformat(candidate)
    except ValueError:
        return None
    if dt.tzinfo is None:
        dt = dt.replace(tzinfo=timezone.utc)
    else:
        dt = dt.astimezone(timezone.utc)
    # Shopify's search-string parser is fine with `YYYY-MM-DDTHH:MM:SSZ`
    # and dislikes microseconds in some date fields. Drop them.
    return dt.strftime("%Y-%m-%dT%H:%M:%SZ")


def _compose_query_filter(existing: Optional[str], since_iso: Optional[str]) -> Optional[str]:
    """Combine an existing user `query` variable with an updated_at predicate.

    Per the incremental contract: if the caller already supplied a custom
    Shopify search string in ``variables.query`` we AND-combine. Otherwise
    we emit a bare predicate. Returns ``None`` (== don't pass `query`)
    when both inputs are empty.
    """
    predicate = f"{_SHOPIFY_UPDATED_AT_FIELD}:>{since_iso}" if since_iso else None
    existing = (existing or "").strip()
    if existing and predicate:
        # Wrap each side in parens to keep predicate boundaries explicit;
        # Shopify's search parser supports AND as a keyword between groups.
        return f"({existing}) AND {predicate}"
    return existing or predicate


# ISO-8601 of the maximum `updatedAt` seen so far across a multi-page export.
# Stored as a tuple (max_string, max_datetime) so comparisons stay correct
# even when strings carry different tz offsets. None == no rows seen.
def _max_updated_at(
    rows: List[Dict[str, Any]],
    current: Optional[Tuple[str, datetime]],
) -> Optional[Tuple[str, datetime]]:
    """Scan ``rows`` for ``updatedAt`` and return the new running max.

    Shopify products / orders / customers / inventory_items each carry an
    ``updatedAt`` field with an ISO-8601 string. We track the textual
    representation we'll persist AND the parsed datetime we use to compare,
    so the comparison is timezone-correct even if Shopify's offset format
    varies between resources.
    """
    best = current
    for row in rows or []:
        if not isinstance(row, dict):
            continue
        raw = row.get("updatedAt")
        if not isinstance(raw, str) or not raw:
            continue
        try:
            dt = datetime.fromisoformat(raw.replace("Z", "+00:00"))
        except ValueError:
            continue
        if dt.tzinfo is None:
            dt = dt.replace(tzinfo=timezone.utc)
        if best is None or dt > best[1]:
            best = (raw, dt)
    return best


